	CALL	I2C_WRITE
	CALL	MARK_ERR
	DJNZ	OLED_FILL_STD1
	CALL	I2C_STOP
	INC	D
	LD	A,D
	CP	8
	JR	C,OLED_FILL_STD0
	RET

OLED_FILL_SH:
	LD	D,0
OLED_FILL_SH0:
	LD	A,0B0H
	ADD	A,D
	CALL	OLED_SEND_CMD
	LD	A,002H			; SH1106 visible area often starts at col +2
	CALL	OLED_SEND_CMD
	LD	A,010H
	CALL	OLED_SEND_CMD
	CALL	OLED_DATA_BEGIN
	LD	B,128
OLED_FILL_SH1:
