OLED_CLEAR:
	LD	D,0
OLED_CLR_PAGE:
	LD	A,0B0H
	ADD	A,D
	CALL	OLED_SEND_CMD
	XOR	A
	CALL	OLED_SEND_CMD
	LD	A,10H
	CALL	OLED_SEND_CMD

	CALL	OLED_DATA_BEGIN
	LD	B,128
OLED_CLR_COL:
	LD	C,00H
	CALL	I2C_WRITE
	CALL	MARK_ERR
	DJNZ	OLED_CLR_COL
	CALL	I2C_STOP

	INC	D
	LD	A,D
	CP	4
	JR	C,OLED_CLR_PAGE
	RET

OLED_HOME:
	LD	A,0B0H
	CALL	OLED_SEND_CMD
	XOR	A
	CALL	OLED_SEND_CMD
	LD	A,10H
	CALL	OLED_SEND_CMD
	RET

PAUSE:
	PUSH	BC
	LD	B,120
PAUSE1:
	CALL	I2C_DLY
	DJNZ	PAUSE1
	POP	BC
	RET

PAUSE_LONG:
	PUSH	BC
	LD	B,255
PAUSE_LONG1:
	CALL	PAUSE
	DJNZ	PAUSE_LONG1
	POP	BC
	RET

OLED_PROBE:
	LD	HL,MSG_PING3C
	CALL	STROUT
	LD	A,OLED_ADDRW
	CALL	OLED_PING_ADDR
	JR	NZ,OLED_PROBE1
	LD	HL,MSG_ACK
	CALL	STROUT
	RET
OLED_PROBE1:
	LD	HL,MSG_NACK2
	CALL	STROUT
	RET

; A = write address byte, returns Z on ACK
OLED_PING_ADDR:
	PUSH	AF
	CALL	I2C_START
	POP	AF
	LD	C,A
	CALL	I2C_WRITE
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET

OLED_WRITE_HELLO:
	CALL	OLED_DATA_BEGIN
	LD	HL,HELLO_DATA
	LD	B,HELLO_LEN
OLED_WRITE_HELLO1:
	LD	C,(HL)
	INC	HL
	CALL	I2C_WRITE
	CALL	MARK_ERR
	DJNZ	OLED_WRITE_HELLO1
	CALL	I2C_STOP
	RET

OLED_SEND_CMD:
	JP	OLED_SEND_CMD0

OLED_SEND_CMD0:
	PUSH	AF
	CALL	I2C_START
	LD	C,OLED_ADDRW
	CALL	I2C_WRITE
	CALL	MARK_ERR
	LD	C,OLED_CTL_CMD
	CALL	I2C_WRITE
	CALL	MARK_ERR
	POP	AF
	LD	C,A
	CALL	I2C_WRITE
	CALL	MARK_ERR
	CALL	I2C_STOP
	RET

OLED_SEND_CMD80:
	PUSH	AF
	CALL	I2C_START
	LD	C,OLED_ADDRW
	CALL	I2C_WRITE
	CALL	MARK_ERR
	LD	C,080H			; Co=1,D/C#=0 single-command framing
	CALL	I2C_WRITE
	CALL	MARK_ERR
	POP	AF
	LD	C,A
	CALL	I2C_WRITE
	CALL	MARK_ERR
	CALL	I2C_STOP
	RET

OLED_DATA_BEGIN:
	CALL	I2C_START
	LD	C,OLED_ADDRW
	CALL	I2C_WRITE
	CALL	MARK_ERR
	LD	C,OLED_CTL_DATA
	CALL	I2C_WRITE
	CALL	MARK_ERR
	RET

OLED_FILL_STD:
	LD	D,0
OLED_FILL_STD0:
	LD	A,0B0H
	ADD	A,D
	CALL	OLED_SEND_CMD
	XOR	A
	CALL	OLED_SEND_CMD
	LD	A,010H
	CALL	OLED_SEND_CMD
	CALL	OLED_DATA_BEGIN
	LD	B,128
OLED_FILL_STD1:
