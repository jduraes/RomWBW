	RET

MARK_ERR:
	RET	Z
	LD	A,1
	LD	(ERRFLG),A
	RET

;------------------------------------------------------------------------------
; SC126 BIT-BANG I2C
;------------------------------------------------------------------------------

I2C_START:
	LD	A,(OPRVAL)
	SET	I2C_SDA,A
	SET	I2C_SCL,A
	CALL	I2C_LATCH
	RES	I2C_SDA,A
	CALL	I2C_LATCH
	RES	I2C_SCL,A
	CALL	I2C_LATCH
	RET

I2C_STOP:
	LD	A,(OPRVAL)
	RES	I2C_SCL,A
	RES	I2C_SDA,A
	CALL	I2C_LATCH
	SET	I2C_SCL,A
	CALL	I2C_LATCH
	SET	I2C_SDA,A
	CALL	I2C_LATCH
	RET

; C = byte to send, returns Z on ACK, NZ on NACK
I2C_WRITE:
	PUSH	BC
	LD	A,(OPRVAL)
	LD	B,8
I2C_WR0:
	RES	I2C_SDA,A
	SLA	C
	JR	NC,I2C_WR1
	SET	I2C_SDA,A
I2C_WR1:
	CALL	I2C_LATCH
	SET	I2C_SCL,A
	CALL	I2C_LATCH
	RES	I2C_SCL,A
	CALL	I2C_LATCH
	DJNZ	I2C_WR0

	SET	I2C_SDA,A
	CALL	I2C_LATCH
	SET	I2C_SCL,A
	CALL	I2C_LATCH
	IN	A,(I2C_BASE)
	BIT	I2C_SDA,A
	LD	A,(OPRVAL)
	RES	I2C_SCL,A
	CALL	I2C_LATCH
	LD	A,1
	JR	NZ,I2C_WR2
	XOR	A
I2C_WR2:
	OR	A
	POP	BC
	RET

I2C_LATCH:
	LD	(OPRVAL),A
	OUT	(I2C_BASE),A
	CALL	I2C_DLY
	RET

I2C_DLY:
	PUSH	BC
	LD	B,64
I2C_DLY1:
	DJNZ	I2C_DLY1
	POP	BC
	RET

;------------------------------------------------------------------------------
; CP/M CONSOLE
;------------------------------------------------------------------------------

STROUT:
STROUT1:
	LD	A,(HL)
	CP	'$'
	RET	Z
	LD	C,A
	CALL	COUT
	INC	HL
	JR	STROUT1

COUT:
	PUSH	AF
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E,C
	LD	C,02H
	CALL	0005H
	POP	HL
	POP	DE
	POP	BC
	POP	AF
	RET

