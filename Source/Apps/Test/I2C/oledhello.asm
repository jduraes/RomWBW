;
	.ECHO	"oledhello\n"
;
; SC126 SSD1306 HELLO WORLD TEST
; Uses Derek's configured SSD1306 address (0x3C, 7-bit).
;
	.ORG	100H

I2C_BASE	.EQU	0CH
I2C_SDA		.EQU	7
I2C_SCL		.EQU	0
I2C_IDLE	.EQU	10001101B

OLED_ADDR7	.EQU	03CH
OLED_ADDRW	.EQU	(OLED_ADDR7 << 1)
OLED_CTL_CMD	.EQU	00H
OLED_CTL_DATA	.EQU	40H

START:
	LD	SP,STACK
	LD	A,I2C_IDLE
	LD	(OPRVAL),A

	LD	HL,MSG_BANNER
	CALL	STROUT
	CALL	OLED_PROBE
	CALL	OLED_BRIGHT_TEST

	LD	A,(ERRFLG)
	OR	A
	JR	Z,START_OK
	LD	HL,MSG_NACK
	CALL	STROUT
	JP	0000H

START_OK:
	LD	HL,MSG_DONE
	CALL	STROUT
	JP	0000H

;------------------------------------------------------------------------------
; OLED HIGH LEVEL
;------------------------------------------------------------------------------

OLED_BRIGHT_TEST:
	LD	HL,MSG_P32
	CALL	STROUT
	CALL	OLED_PROFILE_64
	LD	A,0AFH			; display on
	CALL	OLED_SEND_CMD
	LD	A,0A5H			; entire display on (all pixels lit)
	CALL	OLED_SEND_CMD
	RET

OLED_FORCE_VISIBLE:
	LD	A,0AFH			; display on
	CALL	OLED_SEND_CMD
	LD	A,0A5H			; entire display on
	CALL	OLED_SEND_CMD
	LD	A,0A7H			; inverse on (strong visual cue)
	CALL	OLED_SEND_CMD
	LD	A,0A6H			; and back to normal
	CALL	OLED_SEND_CMD
	RET

