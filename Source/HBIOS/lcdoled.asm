; SC126 I2C BYTE WRITE
; C = BYTE TO SEND
; RETURNS Z ON ACK, NZ ON NACK
;
OLED_I2C_WRITE:
	PUSH	BC
#IF (LCDOLEDSWAP)
	LD	A,(HB_RTCVAL)
	LD	B,8
OLED_I2C_WR0:
	RES	0,A
	SLA	C
	JR	NC,OLED_I2C_WR1
	SET	0,A
OLED_I2C_WR1:
