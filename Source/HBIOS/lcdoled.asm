;
OLED_I2C_START:
#IF (LCDOLEDSWAP)
	LD	A,(HB_RTCVAL)
	OR	OLED_I2CMSK_SW
	CALL	OLED_LATCH
	RES	0,A
	CALL	OLED_LATCH
	RES	7,A
	CALL	OLED_LATCH
#ELSE
