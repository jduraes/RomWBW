;
;==================================================================================================
; HARDWARE SUPPORT FOR SSD1306 OLED ON SC126 WITH HD44780-LIKE TEXT SEMANTICS
;==================================================================================================
;
; THIS DRIVER EMULATES THE TEXT-FACING HD44780 BEHAVIOR USED BY THE LCD DSKY
; CODE PATHS, BUT RENDERS A 20X4 TEXT MODEL TO A 128X64 SSD1306 OLED OVER
; THE SC126 I2C LINES (RTC LATCH: D0=SCL, D7=SDA).
;
; CONFIG OPTIONS (SEE CFG_MASTER.ASM):
;   LCDOLEDADDR: SSD1306 7-BIT I2C ADDRESS ($3C OR $3D)
;   LCDOLEDSWAP: SWAP SCL/SDA RTC LATCH BITS FOR ALTERNATE PANEL WIRING
;
#IF ((LCDENABLE & LCDOLEDENABLE) | (LCDI2CENABLE & LCDOLEDENABLE))
	.ECHO	"*** ERROR: LCDOLEDENABLE CANNOT BE COMBINED WITH LCDENABLE/LCDI2CENABLE!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
LCD_ROWS	.EQU	4
LCD_COLS	.EQU	20
;
LCD_FUNC_CLEAR	.EQU	$01		; CLEAR DISPLAY
LCD_FUNC_HOME	.EQU	$02		; HOME CURSOR & REMOVE ALL SHIFTING
LCD_FUNC_ENTRY	.EQU	$04		; SET CUR DIR AND DISPLAY SHIFT
LCD_FUNC_DISP	.EQU	$08		; DISP, CUR, BLINK ON/OFF
LCD_FUNC_SHIFT	.EQU	$10		; MOVE CUR / SHIFT DISP
LCD_FUNC_SET	.EQU	$20		; SET INTERFACE PARAMS
LCD_FUNC_CGADR	.EQU	$40		; SET CGRAM ADRESS
LCD_FUNC_DDADR	.EQU	$80		; SET DDRAM ADDRESS
;
OLED_ADDRW_CFG	.EQU	(LCDOLEDADDR << 1)
OLED_CTL_CMD	.EQU	$00
OLED_CTL_DATA	.EQU	$40
OLED_SCL		.EQU	%00000001
OLED_SDA		.EQU	%10000000
OLED_I2CMSK	.EQU	(OLED_SCL | OLED_SDA)
OLED_SCL_SW	.EQU	%10000000
OLED_SDA_SW	.EQU	%00000001
OLED_I2CMSK_SW	.EQU	(OLED_SCL_SW | OLED_SDA_SW)
;
; FONT SELECTION: SPLEEN 6X12 RENDERS 12-PIXEL-TALL GLYPHS, SO EACH TEXT
; ROW SPANS TWO SSD1306 PAGES (16 PX) AND ALL 64 VERTICAL PIXELS ARE USED.
; SET TO 0 FOR THE ORIGINAL 5X7 FONT (ONE PAGE PER ROW + CLEARED SPACER).
OLED_FONT_SPLEEN	.EQU	1
;
; FULLER (BOLD) FONT RENDERING FOR THE 5X7 FONT ONLY: EACH GLYPH COLUMN
; IS MERGED WITH THE NEXT COLUMN AND EACH STROKE IS THICKENED VERTICALLY
; BY ONE PIXEL.  SET TO 0 FOR THE ORIGINAL THIN 5X7 FONT.
OLED_FONT_FULL	.EQU	0
;
	DEVECHO	"LCD: OLED I2C ADDR="
	DEVECHO	LCDOLEDADDR
	DEVECHO	", SIZE="
	DEVECHO	LCD_COLS
	DEVECHO	"X"
	DEVECHO	LCD_ROWS
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_LCD	.EQU	$
;
	.DW	SIZ_LCD			; MODULE SIZE
	.DW	LCD_INITPHASE		; ADR OF INIT PHASE HANDLER
;
LCD_INITPHASE:
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,LCD_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,LCD_INIT		; DO INIT
	RET
;
; PREINIT: DETECT OLED, BRING IT UP, POPULATE INITIAL TEXT, REGISTER DSKY DISPATCH
;
LCD_PREINIT:
	; Keep PREINIT side-effect free to avoid early boot lockups.
	; OLED bring-up happens during INIT after console is available.
	RET
;
; POST CONSOLE INITIALIZATION
;
LCD_INIT:
	CALL	NEWLINE
	CALL	PRTSTRD
	.TEXT	"LCD: OLED I2C=0x$"
	LD	A,LCDOLEDADDR
	CALL	PRTHEXBYTE

	CALL	OLED_DETECT
	JR	NZ,LCD_INIT1		; NOT PRESENT, DONE

	LD	A,$FF
	LD	(LCD_PRESENT),A

	; Allow OLED controller charge-pump/power rails to settle before init.
	LD	DE,6250			; ~100ms at 16us ticks
	CALL	VDELAY

	CALL	OLED_INITHW
	JR	NZ,LCD_INIT1		; INIT FAILED, DONE

LCD_INIT0A:
	CALL	LCD_BUF_CLEAR

	LD	HL,$0000		; ROW 0, COL 0
	CALL	LCD_GOTORC
	LD	DE,LCD_STR_BAN
	CALL	LCD_OUTDS

	LD	HL,$0100		; ROW 1, COL 0
	CALL	LCD_GOTORC
	LD	DE,LCD_STR_CPU
	CALL	LCD_OUTDS
	LD	HL,LCD_CPU
	LD	A,(HB_CPUTYPE)
	RLCA
	CALL	ADDHLA
	LD	E,(HL)
	INC	HL
	LD	D,(HL)
	CALL	LCD_OUTDS
	LD	A,'-'
	CALL	LCD_OUTD

	CALL	LCD_EVT_CPUSPD_CORE

	LD	HL,$0200		; ROW 2, COL 0
	CALL	LCD_GOTORC
	LD	DE,LCD_STR_CFG
	CALL	LCD_OUTDS

	CALL	OLED_RENDER
	JR	NZ,LCD_INIT1		; RENDER FAILED, DONE

	LD	BC,LCD_DISPATCH
	CALL	DSKY_SETDISP
;
	CALL	PC_SPACE
	LD	A,LCD_COLS
	CALL	PRTDEC8
	PRTS("X$")
	LD	A,LCD_ROWS
	CALL	PRTDEC8
	XOR	A
	RET
;
LCD_INIT1:
	PRTS(" NOT PRESENT$")
	OR	$FF
	RET
;
; DSKY DEVICE FUNCTION DISPATCH ENTRY
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERR
;   B: FUNCTION (IN)
;
LCD_DISPATCH:
	LD	A,B
	AND	$0F
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_SHOWSEG
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_NULL
	DEC	A
	JP	Z,LCD_DEVICE
	DEC	A
	JP	Z,LCD_MESSAGE
	DEC	A
	JP	Z,LCD_EVENT
	SYSCHKERR(ERR_NOFUNC)
	RET
;
LCD_NULL:
	XOR	A
	RET
;
LCD_SHOWSEG:
	XOR	A
	RET
;
LCD_DEVICE:
	LD	D,DSKYDEV_LCD
	LD	E,0
	LD	H,0
	LD	L,LCDOLEDADDR
	XOR	A
	RET
;
LCD_MESSAGE:
	LD	A,C
	ADD	A,A
	LD	HL,LCD_MSGTBL
	CALL	ADDHLA
	LD	A,(HL)
	INC	HL
	LD	H,(HL)
	LD	L,A
;
	EX	DE,HL
	LD	HL,$0300
	CALL	LCD_GOTORC
	CALL	LCD_LINEOUT
	CALL	OLED_RENDER
	XOR	A
	RET
;
LCD_EVENT:
	LD	A,C
	OR	A
	JR	Z,LCD_EVT_CPUSPD
	DEC	A
	JR	Z,LCD_EVT_DSKACT_NOP
	XOR	A
	RET
;
LCD_EVT_CPUSPD:
	CALL	LCD_EVT_CPUSPD_CORE
	CALL	OLED_RENDER
	XOR	A
	RET
;
LCD_EVT_CPUSPD_CORE:
	LD	HL,$010B		; ROW 1, COL 11 (after "CPU <type>-")
	CALL	LCD_GOTORC
	LD	HL,(CB_CPUKHZ)
	CALL	LCD_PRTD3M
	LD	DE,LCD_STR_MHZ
	CALL	LCD_OUTDS
	RET

; Disk activity events are too frequent for full OLED refresh on bit-banged I2C.
; Ignore this event to avoid severe mass-storage throughput regression.
LCD_EVT_DSKACT_NOP:
	XOR	A
	RET
;
; FORMAT: "Disk #99  R:12345678"
;
LCD_EVT_DSKACT:
	LD	HL,$0300
	CALL	LCD_GOTORC
;
	LD	DE,LCD_STR_IO
	CALL	LCD_OUTDS
;
	LD	A,(HB_DSKUNIT)
	CALL	LCD_EVT_DSKACT_BYTE
;
	LD	A,' '
	CALL	LCD_OUTD
	CALL	LCD_OUTD
;
	LD	A,(HB_DSKFUNC)
	CP	BF_DIOWRITE
	LD	A,'W'
	JR	Z,LCD_EVT_DSKACT0
	LD	A,'R'
LCD_EVT_DSKACT0:
	CALL	LCD_OUTD
;
	LD	A,':'
	CALL	LCD_OUTD
;
	LD	HL,HB_DSKADR+3
	LD	B,4
LCD_EVT_DSKACT1:
	LD	A,(HL)
	CALL	LCD_EVT_DSKACT_BYTE
	DEC	HL
	DJNZ	LCD_EVT_DSKACT1
;
	CALL	OLED_RENDER
	XOR	A
	RET
;
LCD_EVT_DSKACT_BYTE:
	PUSH	AF
	RRCA
	RRCA
	RRCA
	RRCA
	CALL	HEXCONV
	CALL	LCD_OUTD
	POP	AF
	CALL	HEXCONV
	CALL	LCD_OUTD
	RET
;
; SET CURSOR FROM ROW/COL (H=row, L=col)
;
LCD_GOTORC:
	PUSH	HL
	LD	A,H
	LD	HL,LCD_ROWSIDX
	CALL	ADDHLA
	LD	A,(HL)
	POP	HL
	ADD	A,L
	LD	(LCD_CURADDR),A
	RET
;
; SEND FUNCTION CODE IN A (HD44780-LIKE SUBSET)
;
LCD_OUTF:
	CP	LCD_FUNC_CLEAR
	JR	Z,LCD_OUTF_CLR
	CP	LCD_FUNC_HOME
	JR	Z,LCD_OUTF_HOME
	BIT	7,A
	JR	Z,LCD_OUTF_DONE
	AND	$7F
	LD	(LCD_CURADDR),A
	JR	LCD_OUTF_DONE
LCD_OUTF_CLR:
	CALL	LCD_BUF_CLEAR
	JR	LCD_OUTF_DONE
LCD_OUTF_HOME:
	XOR	A
	LD	(LCD_CURADDR),A
LCD_OUTF_DONE:
	XOR	A
	RET
;
; SEND FUNCTION STRING, NULL TERMINATED
;
LCD_OUTFS:
	LD	A,(DE)
	OR	A
	RET	Z
	INC	DE
	CALL	LCD_OUTF
	JR	LCD_OUTFS
;
; SEND DATA BYTE IN A
;
LCD_OUTD:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	C,A
	LD	A,(LCD_CURADDR)
	CALL	LCD_ADDR2IDX
	CP	$FF
	JR	Z,LCD_OUTD1
	LD	L,A
	LD	H,0
	LD	DE,LCD_DDRAM
	ADD	HL,DE
	LD	A,C
	LD	(HL),A
LCD_OUTD1:
	CALL	LCD_CURINC
	POP	HL
	POP	DE
	POP	BC
	RET
;
; SEND STRING, BLANK-PAD TO END OF LINE
;
LCD_LINEOUT:
	LD	B,LCD_COLS
	CALL	LCD_OUTDS
LCD_LINEOUT1:
	LD	A,B
	OR	A
	RET	Z
	LD	A,' '
	CALL	LCD_OUTD
	DJNZ	LCD_LINEOUT1
	RET
;
; SEND DATA STRING
; DE=STRING ADDRESS, NULL TERMINATED
;
LCD_OUTDS:
	LD	A,(DE)
	OR	A
	RET	Z
	INC	DE
	DEC	B
	CALL	LCD_OUTD
	JR	LCD_OUTDS
;
; PRINT VALUE OF HL AS THOUSANDTHS, IE. 0.000
;
LCD_PRTD3M:
	PUSH	BC
	PUSH	DE
	PUSH	HL
	LD	E,'0'
	LD	BC,-10000
	CALL	LCD_PRTD3M1
	LD	E,0
	LD	BC,-1000
	CALL	LCD_PRTD3M1
	LD	A,'.'
	CALL	LCD_OUTD
	LD	BC,-100
	CALL	LCD_PRTD3M1
	LD	C,-10
	CALL	LCD_PRTD3M1
	LD	C,-1
	CALL	LCD_PRTD3M1
	POP	HL
	POP	DE
	POP	BC
	RET
LCD_PRTD3M1:
	LD	A,'0' - 1
LCD_PRTD3M2:
	INC	A
	ADD	HL,BC
	JR	C,LCD_PRTD3M2
	SBC	HL,BC
	CP	E
	JR	Z,LCD_PRTD3M3
	LD	E,0
	CALL	LCD_OUTD
LCD_PRTD3M3:
	RET
;
; CONVERT HD44780 DDRAM ADDRESS IN A TO LINEAR INDEX (0..79)
; RETURNS NZ IF INVALID ADDRESS
;
LCD_ADDR2IDX:
	CP	$14
	JR	C,LCD_ADDR2IDX_OK0
	CP	$28
	JR	C,LCD_ADDR2IDX_ROW2
	CP	$40
	JR	C,LCD_ADDR2IDX_BAD
	CP	$54
	JR	C,LCD_ADDR2IDX_ROW1
	CP	$68
	JR	C,LCD_ADDR2IDX_ROW3
	JR	LCD_ADDR2IDX_BAD
;
LCD_ADDR2IDX_OK0:
	RET
;
LCD_ADDR2IDX_ROW1:
	SUB	$40
	ADD	A,20
	RET
;
LCD_ADDR2IDX_ROW2:
	SUB	$14
	ADD	A,40
	RET
;
LCD_ADDR2IDX_ROW3:
	SUB	$54
	ADD	A,60
	RET
;
LCD_ADDR2IDX_BAD:
	OR	$FF
	RET
;
; INCREMENT CURSOR USING HD44780 20X4 ADDRESS FLOW
;
LCD_CURINC:
	LD	A,(LCD_CURADDR)
	CP	$13
	JR	Z,LCD_CURINC_40
	CP	$53
	JR	Z,LCD_CURINC_14
	CP	$27
	JR	Z,LCD_CURINC_54
	CP	$67
	JR	Z,LCD_CURINC_00
;
	CP	$14
	JR	C,LCD_CURINC_INC
	CP	$28
	JR	C,LCD_CURINC_INC
	CP	$40
	JR	C,LCD_CURINC_00
	CP	$54
	JR	C,LCD_CURINC_INC
	CP	$68
	JR	C,LCD_CURINC_INC
	JR	LCD_CURINC_00
;
LCD_CURINC_INC:
	INC	A
	JR	LCD_CURINC_SET
LCD_CURINC_40:
	LD	A,$40
	JR	LCD_CURINC_SET
LCD_CURINC_14:
	LD	A,$14
	JR	LCD_CURINC_SET
LCD_CURINC_54:
	LD	A,$54
	JR	LCD_CURINC_SET
LCD_CURINC_00:
	XOR	A
LCD_CURINC_SET:
	LD	(LCD_CURADDR),A
	RET
;
LCD_BUF_CLEAR:
	LD	HL,LCD_DDRAM
	LD	(HL),' '
	LD	DE,LCD_DDRAM + 1
	LD	BC,(LCD_ROWS * LCD_COLS) - 1
	LDIR
	XOR	A
	LD	(LCD_CURADDR),A
	RET
;
;--------------------------------------------------------------------------------------------------
; OLED TRANSPORT AND RENDERING
;--------------------------------------------------------------------------------------------------
;
; PING THE PANEL AT THE CONFIGURED ADDRESS, WITH RETRIES TO ABSORB
; OCCASIONAL EARLY-BOOT NACKS.  RETURNS Z IF THE PANEL ACKS, ELSE NZ.
;
OLED_DETECT:
	LD	B,3
OLED_DETECT0:
	PUSH	BC
	CALL	OLED_PING
	POP	BC
	RET	Z
	DJNZ	OLED_DETECT0
	RET
;
OLED_PING:
	CALL	OLED_I2C_START
	LD	C,OLED_ADDRW_CFG
	CALL	OLED_I2C_WRITE
	PUSH	AF
	CALL	OLED_I2C_STOP
	POP	AF
	RET
;
OLED_INITHW:
	LD	HL,OLED_INIT_SEQ
	LD	B,(HL)
	INC	HL
OLED_INITHW1:
	LD	A,(HL)
	CALL	OLED_SEND_CMD
	RET	NZ
	INC	HL
	DJNZ	OLED_INITHW1

	; Brief all-pixels-on pulse confirms panel wake reliably on SC126.
	LD	A,$AF
	CALL	OLED_SEND_CMD
	RET	NZ
	LD	A,$A5
	CALL	OLED_SEND_CMD
	RET	NZ
	LD	DE,3125			; ~50ms at 16us ticks
	CALL	VDELAY
	LD	A,$A4
	CALL	OLED_SEND_CMD
	RET
;
OLED_RENDER:
	LD	A,(LCD_PRESENT)
	OR	A
	RET	Z
;
	LD	HL,LCD_DDRAM		; CURRENT ROW BUFFER POINTER
	LD	D,0			; TEXT ROW INDEX 0..3
;
OLED_RENDER0:
	CALL	OLED_CMD_BEGIN
	JP	NZ,OLED_RENDER_FAIL
	LD	A,D
	ADD	A,A			; map rows to pages 0,2,4,6
	ADD	A,$B0
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$00
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$10
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	CALL	OLED_I2C_STOP
;
	CALL	OLED_DATA_BEGIN
	RET	NZ
;
	LD	B,4
OLED_RENDER_PADL:
	XOR	A
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_PADL
;
#IF (OLED_FONT_SPLEEN)
	PUSH	HL			; SAVE ROW START FOR LOWER-HALF PASS
#ENDIF
	LD	B,LCD_COLS
OLED_RENDER_CH:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	OLED_TXCHAR
	POP	HL
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_CH
;
	LD	B,4
OLED_RENDER_PADR:
	XOR	A
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_PADR
;
	CALL	OLED_I2C_STOP

#IF (OLED_FONT_SPLEEN)
	; Render lower half of this text row to page 1,3,5,7.
	POP	HL			; BACK TO ROW START
	CALL	OLED_CMD_BEGIN
	JP	NZ,OLED_RENDER_FAIL
	LD	A,D
	ADD	A,A
	INC	A			; lower-half page 1,3,5,7
	ADD	A,$B0
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$00
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$10
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	CALL	OLED_I2C_STOP

	CALL	OLED_DATA_BEGIN
	JP	NZ,OLED_RENDER_FAIL
	LD	B,4
OLED_RENDER_PADL2:
	XOR	A
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_PADL2
;
	LD	B,LCD_COLS
OLED_RENDER_CHL:
	LD	A,(HL)
	INC	HL
	PUSH	HL
	CALL	OLED_TXCHAR_L
	POP	HL
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_CHL
;
	LD	B,4
OLED_RENDER_PADR2:
	XOR	A
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_PADR2
	CALL	OLED_I2C_STOP
#ELSE
	; Clear spacer page below this text row.
	CALL	OLED_CMD_BEGIN
	JP	NZ,OLED_RENDER_FAIL
	LD	A,D
	ADD	A,A
	INC	A			; spacer page 1,3,5,7
	ADD	A,$B0
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$00
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	LD	A,$10
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	CALL	OLED_I2C_STOP

	CALL	OLED_DATA_BEGIN
	JP	NZ,OLED_RENDER_FAIL
	LD	B,128
OLED_RENDER_SP1:
	XOR	A
	CALL	OLED_TXBYTE
	JP	NZ,OLED_RENDER_FAIL
	DJNZ	OLED_RENDER_SP1
	CALL	OLED_I2C_STOP
#ENDIF

	INC	D
	LD	A,D
	CP	4
	JP	C,OLED_RENDER0
	XOR	A
	RET
;
OLED_RENDER_FAIL:
	CALL	OLED_I2C_STOP
	OR	$FF
	RET
;
#IF (OLED_FONT_SPLEEN)
; SEND UPPER-HALF COLUMN BYTES FOR CHAR IN A (ROW PAGE 0,2,4,6)
OLED_TXCHAR:
	PUSH	BC
	CALL	OLED_FONTPTR
	JR	OLED_TXCHAR_GO
;
; SEND LOWER-HALF COLUMN BYTES FOR CHAR IN A (ROW PAGE 1,3,5,7)
OLED_TXCHAR_L:
	PUSH	BC
	CALL	OLED_FONTPTR
	LD	BC,6
	ADD	HL,BC			; LOWER BYTES FOLLOW UPPER BYTES
OLED_TXCHAR_GO:
	LD	B,6
OLED_TXCHAR1:
	LD	A,(HL)
	INC	HL
	CALL	OLED_TXBYTE
	JR	NZ,OLED_TXCHAR2
	DJNZ	OLED_TXCHAR1
OLED_TXCHAR2:
	POP	BC
	RET
;
; CHAR IN A -> HL = SPLEEN GLYPH ADDRESS (12 BYTES PER GLYPH)
OLED_FONTPTR:
	SUB	$20
	CP	96
	JR	C,OLED_FONTPTR0
	LD	A,'?' - $20
OLED_FONTPTR0:
	LD	L,A
	LD	H,0
	ADD	HL,HL
	ADD	HL,HL			; *4
	PUSH	HL
	POP	BC			; BC = *4
	ADD	HL,HL			; *8
	ADD	HL,BC			; *12
	LD	BC,OLED_FONT6X12
	ADD	HL,BC
	RET
#ELSE
OLED_TXCHAR:
	PUSH	BC
	SUB	$20
	CP	96
	JR	C,OLED_TXCHAR0
	LD	A,'?' - $20
OLED_TXCHAR0:
	LD	C,A
	LD	B,0
	LD	L,C
	LD	H,B
	ADD	HL,HL
	ADD	HL,HL
	ADD	HL,BC			; *5
	LD	BC,OLED_FONT5X7
	ADD	HL,BC
#IF (OLED_FONT_FULL)
	LD	B,5
OLED_TXCHAR1:
	LD	A,(HL)			; CURRENT COLUMN
	INC	HL
	DEC	B			; LAST COLUMN?
	JR	Z,OLED_TXCHAR2
	OR	(HL)			; MERGE NEXT COLUMN (HORIZONTAL THICKEN)
OLED_TXCHAR2:
	LD	C,A
	SRL	A			; LIGHT PIXEL BELOW EACH SET PIXEL
	OR	C			; (VERTICAL THICKEN)
	CALL	OLED_TXBYTE
	JR	NZ,OLED_TXCHAR3
	LD	A,B
	OR	A
	JR	NZ,OLED_TXCHAR1
	XOR	A			; INTER-CHAR SPACE
	CALL	OLED_TXBYTE
OLED_TXCHAR3:
	POP	BC
	RET
#ELSE
	LD	B,5
OLED_TXCHAR1:
	LD	A,(HL)
	CALL	OLED_TXBYTE
	JR	NZ,OLED_TXCHAR2
	INC	HL
