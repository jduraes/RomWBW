	SET	7,A
	CALL	OLED_LATCH
	RES	7,A
	CALL	OLED_LATCH
	DJNZ	OLED_I2C_WR0
;
	SET	0,A			; RELEASE SDA FOR ACK
	CALL	OLED_LATCH
	SET	7,A
	CALL	OLED_LATCH
	IN	A,(RTCIO)
	BIT	0,A
	LD	A,(HB_RTCVAL)
	RES	7,A
	CALL	OLED_LATCH
#ELSE
	LD	A,(HB_RTCVAL)
	LD	B,8
OLED_I2C_WR0:
	RES	7,A
	SLA	C
	JR	NC,OLED_I2C_WR1
	SET	7,A
OLED_I2C_WR1:
	CALL	OLED_LATCH
	SET	0,A
	CALL	OLED_LATCH
	RES	0,A
	CALL	OLED_LATCH
	DJNZ	OLED_I2C_WR0
;
	SET	7,A			; RELEASE SDA FOR ACK
	CALL	OLED_LATCH
	SET	0,A
	CALL	OLED_LATCH
	IN	A,(RTCIO)
	BIT	7,A
	LD	A,(HB_RTCVAL)
	RES	0,A
	CALL	OLED_LATCH
#ENDIF
	LD	A,1
	JR	NZ,OLED_I2C_WR2
	XOR	A
OLED_I2C_WR2:
	OR	A
	POP	BC
	RET
