	CALL	OLED_LATCH
	SET	0,A
	CALL	OLED_LATCH
#ELSE
	LD	A,(HB_RTCVAL)
	RES	0,A
	RES	7,A
	CALL	OLED_LATCH
	SET	0,A
	CALL	OLED_LATCH
	SET	7,A
	CALL	OLED_LATCH
#ENDIF
	RET
