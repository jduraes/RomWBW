;======================================================================
;
;	SAA1099 SOUND CHIP DRIVER
;
;======================================================================
;
; FULL HBIOS SOUND DRIVER FOR THE SAA1099 6-CHANNEL STEREO PSG.
;
; THIS DRIVER TARGETS CARDS WHERE THE SAA1099 A0 PIN IS WIRED TO
; CPU ADDRESS BIT A0 (E.G. THE RC2014 ZED MINI CARD):
;   SAABASE ($FF)      = REGISTER SELECT PORT (A0=1)
;   SAABASE-1 ($FE)    = DATA PORT (A0=0)
;
; NOTE: THE ORIGINAL UPSTREAM DUMMY VERSION OF THIS FILE USED THE
; 16-BIT I/O CONVENTION (A8 AS A0: ADR=$01FF, DATA=$00FF) WHICH
; MATCHES A DIFFERENT CARD VARIANT.  THIS DRIVER USES PLAIN 8-BIT
; PORT WRITES TO SAABASE / SAABASE-1.
;
; THE CHIP IS WRITE-ONLY, SO NO HARDWARE PROBE IS POSSIBLE.  THE
; DRIVER REGISTERS UNCONDITIONALLY WHEN ENABLED.
;
; FREQUENCY FORMULA (8 MHZ CLOCK):
;   FREQ = 15625 * 2^OCTAVE / (511 - M),  M = 8-BIT FREQ REGISTER
;   RANGE: ~31 HZ - 7.81 KHZ (OCTAVE 0-7)
;
; REGISTER MAP:
;   $00-$05  AMPLITUDE (CH0-5, LOW NIBBLE = RIGHT, HIGH NIBBLE = LEFT)
;   $08-$0D  FREQUENCY (CH0-5)
;   $10-$12  OCTAVE (2 CHANNELS PER REGISTER, LOW/HIGH NIBBLE)
;   $14      FREQUENCY ENABLE BITMASK
;   $15      NOISE ENABLE BITMASK
;   $16      NOISE PARAMETERS
;   $18/$19  ENVELOPES
;   $1C      BIT0 = ALL-CHANNELS ENABLE, BIT1 = RESET PULSE
;
;======================================================================
;
SAA_RSEL	.EQU	SAABASE		; REGISTER SELECT PORT (A0=1)
SAA_RDAT	.EQU	SAABASE-1	; DATA PORT (A0=0)
;
SAA_REG_FREQEN	.EQU	$14		; FREQUENCY ENABLE BITMASK REGISTER
SAA_REG_CTRL	.EQU	$1C		; CONTROL REGISTER
;
	DEVECHO	"SAA1099: IO="
	DEVECHO	SAA_RSEL
	DEVECHO	"/"
	DEVECHO	SAA_RDAT
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_SAA	.EQU	$
;
	.DW	SIZ_SAA			; MODULE SIZE
	.DW	SAA_INITPHASE		; ADR OF INIT PHASE HANDLER
;
SAA_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,SAA_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,SAA_INIT		; DO INIT
	RET				; DONE
;
;======================================================================
;
;	DRIVER FUNCTION TABLE AND INSTANCE DATA
;
SAA_FNTBL:
	.DW	SAA_RESET
	.DW	SAA_VOLUME
	.DW	SAA_PERIOD
	.DW	SAA_NOTE
	.DW	SAA_PLAY
	.DW	SAA_QUERY
	.DW	SAA_DURATION
	.DW	SAA_DEVICE
	.DW	SAA_BEEP
;
#IF (($ - SAA_FNTBL) != (SND_FNCNT * 2))
	.ECHO	"*** INVALID SND FUNCTION TABLE ***\n"
	!!!!!
#ENDIF
;
SAA_IDAT	.EQU	0		; NO INSTANCE DATA ASSOCIATED WITH THIS DEVICE
;
;======================================================================
;
;	DEVICE CAPABILITIES AND CONFIGURATION
;
SAA_TONECNT	.EQU	6		; COUNT NUMBER OF TONE CHANNELS
SAA_NOISECNT	.EQU	2		; COUNT NUMBER OF NOISE GENERATORS
;
#INCLUDE "audio.inc"
;
;======================================================================
;
;	DRIVER PRE-INITIALIZATION
;
;	EARLY HARDWARE RESET (SILENCES THE CHIP BEFORE BOOT).
;
SAA_PREINIT:
	CALL	SAA_HWINIT		; RESET CHIP
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
;======================================================================
;
;	DRIVER INITIALIZATION
;
;	ANNOUNCE DEVICE ON CONSOLE.  CHIP IS WRITE-ONLY, SO NO
;	PROBE IS ATTEMPTED; THE DEVICE IS ALWAYS REGISTERED.
;
SAA_INIT:
	CALL	NEWLINE			; ANNOUNCE
	PRTS("SAA1099:$")
;
	PRTS(" IO=0x$")
	LD	A,SAA_RSEL
	CALL	PRTHEXBYTE
	PRTS("/0x$")
	LD	A,SAA_RDAT
	CALL	PRTHEXBYTE
;
	LD	IY, SAA_IDAT		; SETUP FUNCTION TABLE
	LD	BC, SAA_FNTBL		; POINTER TO FUNCTION TABLE
	LD	DE, SAA_IDAT		; DE := INSTANCE DATA PTR
	CALL	SND_ADDENT		; REGISTER AS SOUND DEVICE
;
	CALL	SAA_RESET		; SET DEFAULT CHIP CONFIGURATION
	XOR	A			; SUCCESSFUL INIT
	RET
;
;======================================================================
;	INITIALIZE DEVICE HARDWARE
;======================================================================
;
SAA_HWINIT:
	; CLEAR ALL 32 REGISTERS
	LD	E,0			; VALUE ZERO
	LD	D,0			; START W/ R0
	LD	B,32			; DO ALL 32 REGISTERS
SAA_HWINIT1:
	CALL	SAA_WRTPSG		; WRITE REGISTER
	INC	D			; BUMP TO NEXT
	DJNZ	SAA_HWINIT1		; LOOP
;
	; RESET PULSE, THEN ENABLE ALL CHANNELS
	LD	DE,(SAA_REG_CTRL*256)+$02	; R$1C BIT1 = RESET PULSE
	CALL	SAA_WRTPSG
	LD	DE,(SAA_REG_CTRL*256)+$01	; R$1C BIT0 = ALL-CHANNELS ENABLE
	CALL	SAA_WRTPSG
;
	; CLEAR SHADOW REGISTERS
	XOR	A
	LD	HL,SAA_OCTSHDW
	LD	(HL),A
	INC	HL
	LD	(HL),A
	INC	HL
	LD	(HL),A
	LD	(SAA_FENSHDW),A
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - RESET
;
;	INITIALIZE DEVICE. SET VOLUME OFF. RESET VOLUME AND TONE VARIABLES.
;
;======================================================================
;
SAA_RESET:
	AUDTRACE(SAAT_INIT)
	CALL	SAA_HWINIT		; SET DEFAULT CHIP CONFIGURATION
;
	; RESET DEFAULTS IN CASE OF AN IN-PLACE HBIOS RESTART
	LD	HL,0
	LD	(SAA_PENDING_PERIOD),HL	; SET TONE PERIOD TO ZERO
	LD	(SAA_PENDING_DURATION),HL	; SET DURATION TO ZERO
	XOR	A			; SIGNAL SUCCESS
	LD	(SAA_PENDING_VOLUME),A	; SET VOLUME TO ZERO
	RET				; DONE, A=0 ABOVE
;
;======================================================================
;	SOUND DRIVER FUNCTION - VOLUME
;======================================================================
;
SAA_VOLUME:
	AUDTRACE(SAAT_VOL)
	AUDTRACE_L
	AUDTRACE_CR
;
	LD	A,L			; SCALE VOLUME 0-255
	RRCA				; DOWN TO 4 BITS (0-15)
	RRCA
	RRCA
	RRCA
	AND	$0F
	LD	B,A			; REPLICATE INTO BOTH
	ADD	A,A			; NIBBLES (V | V<<4) FOR
	ADD	A,A			; CENTERED STEREO
	ADD	A,A
	ADD	A,A
	OR	B
	LD	(SAA_PENDING_VOLUME),A	; SAVE AS PENDING VOLUME
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - NOTE
;======================================================================
;
;	ON ENTRY, HL IS THE NOTE TO PLAY.  NOTE VALUE 0 IS B0b/A0#
;	(THE FIRST TABLE ENTRY).  EACH OCTAVE IS 48 EIGHTH-TONES.
;	ON EXIT, HL CONTAINS THE PACKED SAA PERIOD: H = OCTAVE (0-7),
;	L = FREQUENCY REGISTER VALUE.  FALLS THROUGH INTO SAA_PERIOD
;	(WHICH STASHES THE PENDING PERIOD), SAME CONTRACT AS AY_NOTE.
;
;	UNLIKE THE AY PSG, THE SAA1099 HAS A DEDICATED OCTAVE
;	REGISTER, SO OCTAVE SCALING IS DONE BY ADDING THE REQUESTED
;	OCTAVE TO THE TABLE ENTRY'S OCTAVE NIBBLE RATHER THAN BY
;	SHIFTING A LINEAR PERIOD (AUD_NOTE CANNOT BE USED HERE).
;
SAA_NOTE:
	; SEPARATE THE NOTE AND OCTAVE PORTION OF HL
	LD	DE,48			; 48 EIGHTH-TONES PER OCTAVE
	CALL	DIV16			; SEPARATE OCTAVE (BC) AND NOTE (HL)
;
	; LOOKUP THE PACKED PERIOD FOR THE EIGHTH-TONE WITHIN THE OCTAVE
	ADD	HL,HL			; SCALE FOR 2 BYTE TABLE ENTRY SIZE
	LD	DE,SAA_NOTETBL		; BASE OF NOTE TABLE
	ADD	HL,DE			; HL := DESIRED TABLE ENTRY ADR
	LD	A,(HL)			; GET LOW BYTE (FREQ REG) TO A
	INC	HL			; POINT TO HIGH BYTE
	LD	H,(HL)			; GET HIGH BYTE (OCTAVE) TO H
	LD	L,A			; PUT FREQ REG VALUE INTO L
;
	; ADD THE REQUESTED OCTAVE TO THE TABLE ENTRY'S OCTAVE
	LD	A,H			; TABLE OCTAVE (0-7)
	ADD	A,C			; PLUS REQUESTED OCTAVE
	CP	8			; SAA1099 OCTAVE RANGE IS 0-7
	JR	NC,SAA_NOTE1		; TOO HIGH, SIGNAL ERROR
	LD	H,A			; H := FINAL OCTAVE
	JR	SAA_PERIOD		; FALL INTO PERIOD (LIKE AY_NOTE) TO STASH PENDING
;
SAA_NOTE1:
	LD	HL,$FFFF		; REQUESTED NOTE IS TOO HIGH, FALL INTO PERIOD TO FAIL
;
;======================================================================
;	SOUND DRIVER FUNCTION - PERIOD
;
;	DRIVER-SPECIFIC 16-BIT PERIOD VALUE: H = OCTAVE (0-7),
;	L = FREQUENCY REGISTER VALUE.
;======================================================================
;
SAA_PERIOD:
	AUDTRACE(SAAT_PERIOD)
	AUDTRACE_HL
	AUDTRACE_CR
;
	LD	A,H			; IF ZERO - ERROR
	OR	L
	JR	Z,SAA_PERIOD1
;
	LD	A,H			; OCTAVE MUST BE 0-7
	CP	8
	JR	NC,SAA_PERIOD1		; RETURN FAILURE IF TOO LARGE
	LD	(SAA_PENDING_PERIOD),HL	; SAVE AND RETURN SUCCESSFUL
	XOR	A			; SET SUCCESS
	RET
;
SAA_PERIOD1:
	LD	HL,$FFFF		; REQUESTED PERIOD IS INVALID
	LD	(SAA_PENDING_PERIOD),HL	; FOR THE SAA1099, SO
	OR	$FF			; SET PERIOD TO $FFFF
	RET				; AND RETURN FAILURE
;
;======================================================================
;	SOUND DRIVER FUNCTION - PLAY
;	B = FUNCTION
;	C = AUDIO DEVICE
;	D = CHANNEL
;	A = EXIT STATUS
;======================================================================
;
SAA_PLAY:
	AUDTRACE(SAAT_PLAY)
	AUDTRACE_D
	AUDTRACE_CR
;
	LD	A,(SAA_PENDING_PERIOD + 1)	; CHECK THE HIGH BYTE OF THE PERIOD
	INC	A
	JR	NZ,SAA_PLAY1		; PERIOD IS OK, CONTINUE
	OR	$FF			; ELSE INVALID, SIGNAL FAILURE
	RET				; AND RETURN
;
SAA_PLAY1:
	LD	A,D			; SAA1099 HAS 6 TONE CHANNELS (0-5)
	CP	6
	JR	NC,SAA_PLAYERR		; REJECT CHANNELS > 5
;
	PUSH	HL
	PUSH	DE
;
	; WRITE FREQUENCY REGISTER VALUE TO $08+CH
	LD	A,D			; CHANNEL
	ADD	A,$08			; FREQUENCY REGISTER FOR CHANNEL
	LD	D,A
	LD	HL,SAA_PENDING_PERIOD
	LD	E,(HL)			; L := FREQUENCY REGISTER VALUE
	CALL	SAA_WRTPSG
;
	; WRITE OCTAVE NIBBLE TO $10/$11/$12 (2 CHANNELS PER REGISTER)
	POP	DE			; RECALL CHANNEL
	PUSH	DE
	LD	A,D			; CHANNEL
	LD	B,A			; B := CHANNEL
	SRL	A			; A := CHANNEL/2 = SHADOW INDEX
	LD	E,A
	LD	D,0
	LD	HL,SAA_OCTSHDW
	ADD	HL,DE			; HL := SHADOW BYTE ADDRESS
	LD	A,E
	ADD	A,$10			; OCTAVE REGISTER $10-$12
	PUSH	AF			; SAVE REGISTER NUMBER
	LD	A,B			; CHANNEL
	AND	1			; 0 = LOW NIBBLE, 1 = HIGH NIBBLE
	LD	C,A			; C := NIBBLE SELECT
	LD	A,(SAA_PENDING_PERIOD+1)	; OCTAVE VALUE
	LD	B,A			; B := OCTAVE
	LD	A,C
	OR	A
	LD	A,B			; OCTAVE VALUE
	JR	NZ,SAA_PLAY2		; HIGH NIBBLE?
	; LOW NIBBLE (EVEN CHANNEL)
	AND	$0F			; KEEP LOW NIBBLE OF OCTAVE
	LD	B,A
	LD	A,(HL)
	AND	$F0			; KEEP HIGH NIBBLE OF SHADOW
	OR	B
	JR	SAA_PLAY3
SAA_PLAY2:
	; HIGH NIBBLE (ODD CHANNEL)
	AND	$0F
	ADD	A,A			; SHIFT INTO HIGH NIBBLE
	ADD	A,A
	ADD	A,A
	ADD	A,A
	LD	B,A
	LD	A,(HL)
	AND	$0F			; KEEP LOW NIBBLE OF SHADOW
	OR	B
SAA_PLAY3:
	LD	(HL),A			; UPDATE SHADOW
	LD	E,A			; VALUE TO WRITE
	POP	AF			; RECOVER REGISTER NUMBER
	LD	D,A
	CALL	SAA_WRTPSG		; WRITE OCTAVE REGISTER
;
	; WRITE AMPLITUDE REGISTER $00+CH
	POP	DE			; RECALL CHANNEL
	PUSH	DE
	LD	A,D			; CHANNEL
	LD	D,A			; AMPLITUDE REGISTER = $00+CH
	LD	A,(SAA_PENDING_VOLUME)	; PENDING VOLUME (BOTH NIBBLES)
	LD	E,A
	CALL	SAA_WRTPSG		; SET VOLUME IN CHANNEL REG
;
	; SET THE CHANNEL'S BIT IN THE FREQUENCY-ENABLE REGISTER $14
	POP	DE			; RECALL CHANNEL
	LD	A,D			; CHANNEL 0-5
	LD	B,A
	INC	B
	LD	A,1			; COMPUTE BIT MASK 1<<CH
SAA_PLAY4:
	DEC	B
	JR	Z,SAA_PLAY5
	ADD	A,A
	JR	SAA_PLAY4
SAA_PLAY5:
	LD	B,A			; B := CHANNEL BIT MASK
	LD	A,(SAA_FENSHDW)	; FREQ-ENABLE SHADOW
	OR	B			; SET THIS CHANNEL'S BIT
	LD	(SAA_FENSHDW),A		; UPDATE SHADOW
	LD	E,A
	LD	D,SAA_REG_FREQEN
	CALL	SAA_WRTPSG
;
	POP	HL
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
SAA_PLAYERR:
	OR	$FF			; INVALID CHANNEL
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - QUERY AND SUBFUNCTIONS
;======================================================================
;
SAA_QUERY:
	LD	A, E
	CP	BF_SNDQ_CHCNT		; SUB FUNCTION 01
	JR	Z, SAA_QUERY_CHCNT
;
	CP	BF_SNDQ_VOLUME		; SUB FUNCTION 02
	JR	Z, SAA_QUERY_VOLUME
;
	CP	BF_SNDQ_PERIOD		; SUB FUNCTION 03
	JR	Z, SAA_QUERY_PERIOD
;
	CP	BF_SNDQ_DEV		; SUB FUNCTION 04
	JR	Z, SAA_QUERY_DEV
;
	OR	$FF			; SIGNAL FAILURE
	RET
;
SAA_QUERY_CHCNT:
	LD	BC,(SAA_TONECNT*256)+SAA_NOISECNT	; RETURN NUMBER OF
	XOR	A					; TONE AND NOISE
	RET						; CHANNELS IN BC
;
SAA_QUERY_PERIOD:
	LD	HL,(SAA_PENDING_PERIOD)	; RETURN 16-BIT PERIOD
	XOR	A			; IN HL REGISTER
	RET
;
SAA_QUERY_VOLUME:
	LD	A,(SAA_PENDING_VOLUME)	; RETURN 8-BIT VOLUME
	LD	L,A			; IN L REGISTER
	XOR	A
	RET
;
SAA_QUERY_DEV:
	LD	B,SNDDEV_SAA			; RETURN DEVICE IDENTIFIER
	LD	DE,(SAA_RSEL*256)+SAA_RDAT	; AND ADDRESS AND DATA PORT
	XOR	A
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - DURATION
;======================================================================
;
SAA_DURATION:
	LD	(SAA_PENDING_DURATION),HL	; SET TONE DURATION
	XOR	A
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - DEVICE
;======================================================================
;
SAA_DEVICE:
	LD	D,SNDDEV_SAA		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL UNIT
	LD	C,$00			; C := DEVICE TYPE
	LD	H,0			; H := MODE (NONE)
	LD	L,SAA_RSEL		; L := BASE I/O ADDRESS
	XOR	A
	RET
;
;======================================================================
;	SOUND DRIVER FUNCTION - BEEP
;======================================================================
;
SAA_BEEP:
	JP	SND_BEEP		; DEFER TO GENERIC CODE IN HBIOS
;
;======================================================================
;
; 	WRITE DATA IN E REGISTER TO DEVICE REGISTER D
;	INTERRUPTS DISABLED DURING WRITE. WRITE IN SLOW MODE IF Z180 CPU.
;
;======================================================================
;
SAA_WRTPSG:
#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)		; GET CURRENT RTC LATCH VALUE
	OR	%00001000		; SBC-V2-004 CHANGE
	OUT	(RTCIO),A		; TO HALF CLOCK SPEED
#ENDIF
#IF (CPUFAM == CPU_Z180)
	IN0	A,(Z180_DCNTL)		; GET WAIT STATES
	PUSH	AF			; SAVE VALUE
	OR	%00110000		; FORCE SLOW OPERATION (I/O W/S=3)
	OUT0	(Z180_DCNTL),A		; AND UPDATE DCNTL
#ENDIF
	LD	A,D			; SELECT THE REGISTER WE
	EZ80_IO
	OUT	(SAA_RSEL),A		; WANT TO WRITE TO
	LD	A,E			; WRITE THE VALUE TO
	EZ80_IO
	OUT	(SAA_RDAT),A		; THE SELECTED REGISTER
#IF (CPUFAM == CPU_Z180)
	POP	AF			; GET SAVED DCNTL VALUE
	OUT0	(Z180_DCNTL),A		; AND RESTORE IT
#ENDIF
#IFDEF SBCV2004
	LD	A,(HB_RTCVAL)		; SBC-V2-004 CHANGE TO
	OUT	(RTCIO),A		; NORMAL CLOCK SPEED
#ENDIF
	RET
;
;======================================================================
;
SAA_PENDING_PERIOD	.DW	0	; PENDING PERIOD (H=OCTAVE, L=FREQ)
SAA_PENDING_VOLUME	.DB	0	; PENDING VOL (8 BITS, BOTH NIBBLES)
SAA_PENDING_DURATION	.DW	0	; PENDING DURATION (16 BITS)
;
SAA_OCTSHDW		.DB	0,0,0	; SHADOW OF OCTAVE REGISTERS $10-$12
SAA_FENSHDW		.DB	0	; SHADOW OF FREQ-ENABLE REGISTER $14
;
#IF AUDIOTRACE
SAAT_INIT		.DB	"\r\nSAA_INIT\r\n$"
SAAT_VOL		.DB	"\r\nSAA_VOLUME: $"
SAAT_PERIOD		.DB	"\r\nSAA_PERIOD $"
SAAT_PLAY		.DB	"\r\nSAA_PLAY CH: $"
#ENDIF
;
;======================================================================
;	EIGHTH TONE FREQUENCY TABLE
;======================================================================
;
; THE FOLLOWING TABLE MAPS A FULL OCTAVE OF EIGHTH-TONES STARTING
; AT A0#/B0b (HBIOS NOTE CODE 0) TO THE PACKED SAA1099 PERIOD VALUE
; (OCTAVE REGISTER VALUE << 8 | FREQUENCY REGISTER VALUE).
;
; THE FREQUENCY PRODUCED BY THE SAA1099 AT 8 MHZ CLOCK IS:
;   FREQ = 15625 * 2^OCTAVE / (511 - M)
;
; ENTRIES ARE COMPUTED FOR OCTAVE 0 (FREQ RANGE 30.58-61.03 HZ);
; HIGHER OCTAVES ARE REACHED BY ADDING TO THE OCTAVE NIBBLE IN
; SAA_NOTE.  NOTES 0-3 ARE BELOW THE OCTAVE-0 FLOOR AND ARE
; CLAMPED TO M=0 (30.58 HZ).
;
; THE TARGET FREQUENCIES MATCH THE AY DRIVER'S TABLE SO THAT
; SND_NOTE SEMANTICS ARE CONSISTENT ACROSS DRIVERS.
;
SAA_NOTETBL:
	.DW	$0000		; A0#/B0b  29.13 HZ (CLAMPED, MIN IS 30.58)
	.DW	$0000		;          29.56 HZ (CLAMPED)
	.DW	$0000		;          29.99 HZ (CLAMPED)
	.DW	$0000		;          30.42 HZ (CLAMPED)
	.DW	$0005		; B0       30.86 HZ
	.DW	$000C		;          31.31 HZ
	.DW	$0013		;          31.77 HZ
	.DW	$001A		;          32.23 HZ
	.DW	$0021		; C1       32.70 HZ
	.DW	$0028		;          33.18 HZ
	.DW	$002F		;          33.66 HZ
	.DW	$0035		;          34.15 HZ
	.DW	$003C		; C1#/D1b  34.64 HZ
	.DW	$0042		;          35.15 HZ
	.DW	$0049		;          35.66 HZ
	.DW	$004F		;          36.18 HZ
	.DW	$0055		; D1       36.70 HZ
	.DW	$005B		;          37.24 HZ
	.DW	$0061		;          37.78 HZ
	.DW	$0067		;          38.33 HZ
	.DW	$006D		; D1#/E1b  38.89 HZ
	.DW	$0073		;          39.45 HZ
	.DW	$0079		;          40.03 HZ
	.DW	$007E		;          40.61 HZ
	.DW	$0084		; E1       41.20 HZ
	.DW	$0089		;          41.80 HZ
	.DW	$008F		;          42.41 HZ
	.DW	$0094		;          43.02 HZ
	.DW	$0099		; F1       43.65 HZ
	.DW	$009E		;          44.28 HZ
	.DW	$00A3		;          44.93 HZ
	.DW	$00A8		;          45.58 HZ
	.DW	$00AD		;          46.24 HZ
	.DW	$00B2		; F1#/G1b  46.92 HZ
	.DW	$00B7		;          47.60 HZ
	.DW	$00BB		;          48.29 HZ
	.DW	$00C0		;          48.99 HZ
	.DW	$00C5		; G1       49.71 HZ
	.DW	$00C9		;          50.43 HZ
	.DW	$00CE		;          51.16 HZ
	.DW	$00D2		;          51.91 HZ
	.DW	$00D6		; G1#/A1b  52.66 HZ
	.DW	$00DB		;          53.43 HZ
	.DW	$00DF		;          54.21 HZ
	.DW	$00E3		;          54.99 HZ
	.DW	$00E7		; A1       55.79 HZ
	.DW	$00EB		;          56.61 HZ
	.DW	$00EF		;          57.43 HZ
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_SAA	.EQU	$
SIZ_SAA	.EQU	END_SAA - ORG_SAA
;
	MEMECHO	"SAA occupies "
	MEMECHO	SIZ_SAA
	MEMECHO	" bytes.\n"
