;==================================================================================================
; DS3231 I2C CLOCK DRIVER
;
; LABELS STARTING WITH I2C ARE REFERENCING THE I2C LIBRARY (I2CPCF OR I2CBIT)
;
; DS3231 REGISTER MAP USED:
;   00H SECONDS (BCD 00-59)
;   01H MINUTES (BCD 00-59)
;   02H HOURS   (BIT6=0: 24HR BCD 00-23; BIT6=1: 12HR + BIT5 AM/PM)
;   03H DAY OF WEEK (1-7, IGNORED)
;   04H DATE    (BCD 01-31)
;   05H MONTH   (BIT7=CENTURY, BITS 4-0 BCD 01-12)
;   06H YEAR    (BCD 00-99)
;   0EH CONTROL (BIT7 /EOSC, BIT2 INTCN, BITS4:3 RS, BIT1 A2IE, BIT0 A1IE)
;   0FH STATUS  (BIT7 OSF OSCILLATOR STOP FLAG, BIT3 EN32KHZ)
;
; THE DS3231 CHIP ITSELF HAS NO NVRAM.  IF AN AT24C32 EEPROM IS
; DETECTED AT I2C ADDRESS 57H (PRESENT ON THE ZS-042 MODULE),
; BF_RTCGETBYT/SETBYT ARE SERVED FROM IT (INDICES 00H-FFH MAP TO
; EEPROM BYTES 0000H-00FFH); WITHOUT THE EEPROM THEY RETURN
; ERR_NOTIMPL.  GETBLK/SETBLK AND ALARMS ARE NOT IMPLEMENTED.
;
;==================================================================================================
;
#IF (!(I2CPCFENABLE | I2CBITENABLE))
	.ECHO	"*** DS3231 DRIVER REQUIRES I2CPCFENABLE OR I2CBITENABLE!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
DS3231_DEV	.EQU	68H		; DEVICE IDENTIFIER
DS3231_W	.EQU	00000000B	; DEVICE WRITE
DS3231_R	.EQU	00000001B	; DEVICE READ
;
DS3_READ	.EQU	(DS3231_DEV << 1 | DS3231_R)
DS3_WRITE	.EQU	(DS3231_DEV << 1 | DS3231_W)
;
DS3_EE_DEV	.EQU	57H		; AT24C32 EEPROM (ZS-042 MODULE)
DS3_EE_READ	.EQU	(DS3_EE_DEV << 1 | DS3231_R)
DS3_EE_WRITE	.EQU	(DS3_EE_DEV << 1 | DS3231_W)
;
DS3231_REG_SEC	.EQU	00H
DS3231_REG_HRS	.EQU	02H
DS3231_REG_MON	.EQU	05H
DS3231_REG_CTL	.EQU	0EH
DS3231_REG_STA	.EQU	0FH
;
DS3231_CTL_INIT	.EQU	00000000B	; /EOSC=0 (RUN), INTCN=0 (SQW), RS=1HZ
DS3231_STA_OSF	.EQU	10000000B	; OSCILLATOR STOP FLAG
;
	DEVECHO	"DS3231: I2C ADDR="
	DEVECHO	DS3231_DEV
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_DS3231	.EQU	$
;
	.DW	SIZ_DS3231		; MODULE SIZE
	.DW	DS3231_INITPHASE	; ADR OF INIT PHASE HANDLER
;
DS3231_INITPHASE:
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,DS3231RTC_INIT	; DO INIT
	RET				; DONE
;
;-----------------------------------------------------------------------------
; DS3231 INITIALIZATION
;
; ASSUMES I2C HAS ALREADY BEEN INITIALIZED.
; PROBES ADDRESS 68H, INITIALISES THE CONTROL REGISTER, REPORTS THE
; OSCILLATOR STOP FLAG, DISPLAYS THE CURRENT DATE/TIME AND REGISTERS
; AS THE HBIOS RTC IF NO OTHER RTC HAS CLAIMED THE DISPATCHER.
;
DS3231RTC_INIT:
	CALL	NEWLINE			; FORMATTING
;
	; DCD FLOATING-LINE GUARD (RUNS FIRST, BEFORE ANY I2C CHECK:
	; THE STORM EXISTS WHENEVER THE TICK WIRE IS UNDRIVEN, EVEN IF
	; THE RTC OR THE WHOLE SC137 IS ABSENT).  THE TICK COMES FROM
	; THE DS3231 1HZ SQW OUTPUT WIRED TO UART0'S DCD PIN (SEE
	; UART.ASM).  IF THE SC137 IS REMOVED, THE WIRE LEAVES DCD
	; FLOATING AND NOISE FIRES THE MODEM STATUS INTERRUPT IN A
	; STORM THAT STARVES THE SYSTEM.  COUNT DELTA-DCD EVENTS OVER
	; A ~90MS WINDOW: A DRIVEN 1HZ SQW YIELDS AT MOST ONE EDGE, A
	; FLOATING LINE YIELDS MANY.  ON STORM: MASK THE MODEM STATUS
	; INTERRUPT AT THE SOURCE (IER BIT 3) AND REMEMBER IT IN
	; DS3_DCDST SO THE TICK HOOK IS SKIPPED BELOW; DS3_TICKOK
	; STAYS CLEAR, SO DS3_GETTIM FALLS BACK TO REAL BUS READS
	; (DEGRADED MODE).
	DI				; STOP THE ISR EATING DELTAS
	LD	C,UART0BASE+6		; MSR PORT
	IN	A,(C)			; CLEAR PENDING DELTA BITS
	LD	B,100			; 100 SAMPLES, ~1MS APART
	LD	H,0			; DELTA-DCD COUNT
DS3_DCDCHK1:
	LD	DE,60			; ~1MS
	CALL	VDELAY			; CLOBBERS A/DE, KEEPS BC/HL
	LD	C,UART0BASE+6
	IN	A,(C)			; READ MSR (CLEARS DELTAS)
	AND	%00001000		; DELTA DCD?
	JR	Z,DS3_DCDCHK2
	INC	H
DS3_DCDCHK2:
	DJNZ	DS3_DCDCHK1
	EI
	XOR	A
	LD	(DS3_DCDST),A		; ASSUME LINE DRIVEN
	LD	A,H
	CP	4			; >=4 EDGES IN ~90MS = FLOATING
	JR	C,DS3_DCDOK
;
	LD	C,UART0BASE+1		; IER PORT (READABLE ON 16550)
	IN	A,(C)
	AND	%11110111		; CLEAR MODEM STATUS INT ENABLE
	OUT	(C),A
	PRTS(" DCD-FLT$")		; VISIBILITY: GUARD FIRED
	LD	A,1
	LD	(DS3_DCDST),A		; STORM MASKED, SKIP TICK HOOK
DS3_DCDOK:
;
	PRTS("DS3231: $")		; ANNOUNCE DRIVER
;
	PRTS("I2C ADDR=0x$")
	LD	A,DS3231_DEV
	CALL	PRTHEXBYTE
	CALL	PC_SPACE
;
	LD	A,(I2C_FAIL_FLAG)	; CHECK IF THE
	OR	A			; I2C DRIVER
	JP	NZ,DS3231_INIT_FAIL	; INITIALIZED
;
	CALL	DS3_DETECT		; PROBE FOR HARDWARE VIA I2C ACK
	JP	NZ,DS3231_INIT_NOACK	; NOT PRESENT
;
	CALL	DS3_INITCTL		; CONTROL REGISTER: OSC ON, 24HR SQW MODE
	JP	NZ,DS3231_INIT_NOACK
;
	CALL	DS3_RDSTA		; READ STATUS REGISTER
	JP	NZ,DS3231_INIT_NOACK
	BIT	7,A			; OSF SET?
	JR	Z,DS3231_NOOSF
	PRTS("OSC-STOPPED$")		; TIME IS INVALID UNTIL SET
	CALL	PC_SPACE
DS3231_NOOSF:
;
	CALL	DS3_RDC			; READ CLOCK DATA
	JP	NZ,DS3231_INIT_NOACK
	CALL	DS3_DISP		; DATE AND TIME
;
	CALL	DS3_XLAT		; PRIME THE SOFT CLOCK
;
	; INITIALISE SOFT-CLOCK STATE
	XOR	A
	LD	(DS3_TICKOK),A		; NO TICK OBSERVED YET
	LD	(DS3_SYNCF),A		; NO RESYNC PENDING
	LD	HL,DS3_RESYNC		; ARM THE RESYNC COUNTDOWN
	LD	(DS3_SYNCCNT),HL
;
	; SKIP THE TICK HOOK IF THE FLOATING-LINE GUARD (TOP OF INIT)
	; MASKED A DCD STORM.
	LD	A,(DS3_DCDST)		; DCD STORM MASKED?
	OR	A
	JR	Z,DS3_DCDHOOK
	PRTS(" TICK-OFF$")		; DEGRADED: NO SOFT-CLOCK TICK
	CALL	PC_SPACE
	JR	DS3_NOHOOK
;
DS3_DCDHOOK:
	; HOOK THE SECONDS VECTOR FOR THE SOFT CLOCK.  THE TICK COMES
	; FROM THE DS3231 1HZ SQW OUTPUT WIRED TO THE UART DCD PIN
	; (MODEM STATUS INTERRUPT -> HB_TIMINT, SEE UART.ASM).
	LD	HL,(VEC_SECOND+1)	; SAVE EXISTING HANDLER
	LD	(DS3_SECCHAIN+1),HL	; ... FOR CHAINING
	LD	HL,DS3_SEC
	LD	(VEC_SECOND+1),HL	; INSTALL SOFT-CLOCK HANDLER
DS3_NOHOOK:
;
	; PROBE FOR AT24C32 EEPROM AT 57H (ZS-042 MODULE NVRAM)
	XOR	A
	LD	(DS3_EEP),A		; ASSUME ABSENT
	LD	A,DS3_EE_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_ACK	; DID IT ACK?
	PUSH	AF
	CALL	I2C_STOP		; RELEASE BUS EITHER WAY
	POP	AF
	JR	NZ,DS3_NOEEP
	LD	A,1
	LD	(DS3_EEP),A		; EEPROM PRESENT
	CALL	PRTSTRD			; (NOT PRTS: TASM MANGLES LONG MACRO ARGS)
	.TEXT	" NVRAM=AT24C32$"
DS3_NOEEP:
;
	LD	A,(RTC_DISPACT)		; CHECK RTC DISPATCHER STATUS.
	OR	A			; RETURN NOW IF WE ALREADY HAVE
	RET	NZ			; A PRIMARY RTC INSTALLED.
;
	LD	BC,DS3_DISPATCH		; SETUP CLOCK HBIOS DISPATCHER
	CALL	RTC_SETDISP
;
	XOR	A			; SIGNAL SUCCESS
	RET
;
; I2C IS FINE, DS3231 ITSELF DIDN'T ACK
;
DS3231_INIT_NOACK:
	PRTS("NOT PRESENT$")		; EXIT
	PUSH	AF			; WITH ERROR
	JR	DS3231_INIT_ERR
;
DS3231_INIT_FAIL:			; EXIT
	PRTS("I2C FAILURE$")		; WITH ERROR MESSAGE
	PUSH	AF
DS3231_INIT_ERR:
	POP	AF
	LD	A,ERR_NOHW		; ERROR
	OR	A			; STATUS
	RET
;
;-----------------------------------------------------------------------------
; DS3231 HBIOS DISPATCHER
;
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERROR
;   B: FUNCTION (IN)
;
DS3_DISPATCH:
	PUSH	AF			; CHECK IF WE
	LD	A,(I2C_FAIL_FLAG)	; HAVE HARDWARE
	OR	A			; AND ASSOCIATED
	JR	NZ,DS3231_INIT_ERR	; DRIVER
	POP	AF
;
	LD	A,B			; GET REQUESTED FUNCTION
	AND	$0F			; ISOLATE SUB-FUNCTION
	JP	Z,DS3_GETTIM		; GET TIME
	DEC	A
	JP	Z,DS3_SETTIM		; SET TIME
	DEC	A
	JP	Z,DS3_GETBYT		; GET NVRAM BYTE (AT24C32 IF PRESENT)
	DEC	A
	JP	Z,DS3_SETBYT		; SET NVRAM BYTE (AT24C32 IF PRESENT)
	DEC	A
	JP	Z,DS3_NOFUNC		; GET NVRAM BLOCK (NOT IMPLEMENTED)
	DEC	A
	JP	Z,DS3_NOFUNC		; SET NVRAM BLOCK (NOT IMPLEMENTED)
	DEC	A
	JP	Z,DS3_NOFUNC		; GET ALARM (NOT IMPLEMENTED)
	DEC	A
	JP	Z,DS3_NOFUNC		; SET ALARM (NOT IMPLEMENTED)
	DEC	A
	JP	Z,DS3_DEVICE		; REPORT RTC DEVICE INFO
	SYSCHKERR(ERR_NOFUNC)
	RET
;
; GETBLK/SETBLK AND ALARMS ARE NOT IMPLEMENTED (MATCHES DS7RTC).
; NVRAM BYTES NEED THE AT24C32 (SEE DS3_GETBYT/DS3_SETBYT).
;
DS3_NOFUNC:
	SYSCHKERR(ERR_NOTIMPL)
	RET
;
;-----------------------------------------------------------------------------
; DS3231 GET TIME
;
; HL POINTS TO A BUFFER TO STORE THE CURRENT TIME AND DATE IN.
; THE TIME AND DATE INFORMATION MUST BE TRANSLATED TO THE
; HBIOS FORMAT AND COPIED FROM THE HBIOS DRIVER BANK TO
; CALLER INVOKED BANK.
;
; HBIOS FORMAT  = YYMMDDHHMMSS
; DS3231 FORMAT = SSMMHH..DDMMYY..
;
; THE DRIVER KEEPS A BCD SOFT CLOCK (DS3_SOFT) ADVANCED ONCE PER
; SECOND VIA VEC_SECOND, DRIVEN BY THE DS3231'S OWN 1HZ SQW OUTPUT
; WIRED TO THE UART DCD PIN (SEE UART.ASM).  GETTIM IS THEN A PURE
; RAM COPY WITH ZERO I2C TRAFFIC.  EVERY DS3_RESYNC SECONDS THE
; VEC_SECOND HANDLER SETS DS3_SYNCF AND THE NEXT GETTIM PERFORMS A
; REAL BUS READ TO SELF-HEAL AGAINST ANY MISSED TICK.  IF NO TICK
; IS EVER OBSERVED (SQW NOT WIRED), DS3_TICKOK STAYS CLEAR AND
; EVERY GETTIM DOES A REAL BUS READ (FALLBACK MODE).
;
DS3_RESYNC	.EQU	3600		; SECONDS BETWEEN BUS RE-SYNCS
;
DS3_GETTIM:
	LD	A,(DS3_TICKOK)		; TICK OBSERVED?
	OR	A
	JR	Z,DS3_GT_REAL		; NO: FALLBACK, REAL BUS READ
	LD	A,(DS3_SYNCF)		; RESYNC DUE?
	OR	A
	JR	Z,DS3_GT_SOFT		; NO: SERVE THE SOFT CLOCK
;
DS3_GT_REAL:
	PUSH	HL			; SAVE DESTINATION
	CALL	DS3_RDC			; READ THE CLOCK INTO THE BUFFER
	JR	NZ,DS3_GETTIM_ERR	; BAIL IF READ FAILED, BUFFER IS GARBAGE
	CALL	DS3_XLAT		; TRANSLATE INTO THE SOFT CLOCK
	XOR	A			; CLEAR THE RESYNC FLAG
	LD	(DS3_SYNCF),A
	POP	DE			; DE POINTS TO DESTINATION
	LD	HL,DS3_SOFT		; HL POINTS TO SOURCE
	JR	DS3_GT_OUT
;
DS3_GT_SOFT:
	EX	DE,HL			; DESTINATION TO DE
	LD	HL,DS3_SOFT		; SOURCE IS THE SOFT CLOCK
;
DS3_GT_OUT:
	LD	A,BID_BIOS		; COPY FROM BIOS BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,(HB_INVBNK)		; COPY TO CURRENT USER BANK
	LD	(HB_DSTBNK),A		; SET IT
	LD	BC,6			; LENGTH IS 6 BYTES
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY		; COPY THE CLOCK DATA
#IF (INTMODE == 1)
	EI
#ENDIF
	XOR	A			; SIGNAL SUCCESS
	RET
;
DS3_GETTIM_ERR:
	POP	HL			; DISCARD SAVED DESTINATION, NOT WRITING TO IT
	RET				; NZ ALREADY SET BY DS3_RDC
;
;-----------------------------------------------------------------------------
; TRANSLATE DS3_BUF (DS3231 ORDER SS MM HH .. DD MM YY ..) INTO THE
; SOFT CLOCK DS3_SOFT (HBIOS ORDER YY MM DD HH MM SS), APPLYING THE
; 24-HOUR AND CENTURY MASKS.
;
DS3_XLAT:
	LD	HL,DS3_BUF+2
	LD	DE,DS3_BUF+3		; TRANSLATE
	LD	B,3			; FORMAT
DS3_XL0:
	LD	A,(HL)
	LD	(DE),A
	INC	DE
	LD	A,(DE)
	LD	(HL),A
	DEC	HL
	DJNZ	DS3_XL0
;
	LD	A,(DS3_BUF+3)		; HOURS: FORCE 24HR MASK
	AND	00111111B
	LD	(DS3_BUF+3),A
	LD	A,(DS3_BUF+1)		; MONTH: STRIP CENTURY BIT
	AND	00011111B
	LD	(DS3_BUF+1),A
;
	LD	HL,DS3_BUF		; COPY INTO THE SOFT CLOCK
	LD	DE,DS3_SOFT
	LD	BC,6
#IF (INTMODE == 1)
	DI				; ATOMIC WRT THE TICK ISR
#ENDIF
	LDIR
#IF (INTMODE == 1)
	EI
#ENDIF
	RET
;
;-----------------------------------------------------------------------------
; DS3231 SET TIME
;
;   A: RESULT (OUT), 0=OK, Z=OK, NZ=ERROR
;   HL: DATE/TIME BUFFER (IN)
;
; HBIOS FORMAT  = YYMMDDHHMMSS
; DS3231 FORMAT = SSMMHH..DDMMYY..
;
; FORCES 24-HOUR MODE AND CLEARS OSF AFTER A VALID WRITE.
;
DS3_SETTIM:
	LD	A,(HB_INVBNK)		; COPY FROM CURRENT USER BANK
	LD	(HB_SRCBNK),A		; SET IT
	LD	A,BID_BIOS		; COPY TO BIOS BANK
	LD	(HB_DSTBNK),A		; SET IT
	LD	DE,DS3_BUF		; DESTINATION ADDRESS
	LD	BC,6			; LENGTH IS 6 BYTES
#IF (INTMODE == 1)
	DI
#ENDIF
	CALL	HB_BNKCPY		; COPY THE CLOCK DATA
#IF (INTMODE == 1)
	EI
#ENDIF
;
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_WRITE		; SET SLAVE ADDRESS
	CALL	I2C_START_ADDR		; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN	; AND ISSUE THE SLAVE ADDRESS
	JP	NZ,DS3_SET_ERR
;
	LD	A,DS3231_REG_SEC	; REGISTER 00
	CALL	I2C_PUTBYTE_PIN		; PUT ADDRESS ON BUS
	JP	NZ,DS3_SET_ERR
;
	; REARRANGE HBIOS YYMMDDHHMMSS INTO DS3231 SSMMHH..DDMMYY
	LD	HL,DS3_BUF
	LD	A,(HL)			; YY
	PUSH	AF
	LD	A,(DS3_BUF+1)		; MM
	PUSH	AF
	LD	A,(DS3_BUF+2)		; DD
	PUSH	AF
	LD	A,(DS3_BUF+3)		; HH
	LD	(DS3_BUF+2),A
	LD	A,(DS3_BUF+4)		; MIN
	LD	(DS3_BUF+1),A
	LD	A,(DS3_BUF+5)		; SS
	LD	(DS3_BUF+0),A
	POP	AF
	LD	(DS3_BUF+4),A		; DD
	POP	AF
	LD	(DS3_BUF+5),A		; MM
	POP	AF
	LD	(DS3_BUF+6),A		; YY
	LD	A,1			; DAY OF WEEK = 1 (UNUSED)
	LD	(DS3_BUF+3),A
;
	LD	A,(DS3_BUF+2)		; HOURS: FORCE 24-HOUR MODE
	AND	00111111B		; (BIT6=0) AND BCD RANGE
	LD	(DS3_BUF+2),A
	LD	A,(DS3_BUF+5)		; MONTH: KEEP CENTURY CLEAR
	AND	00011111B
	LD	(DS3_BUF+5),A
;
	LD	HL,DS3_BUF
	LD	B,7
DS3_ST1:
	LD	A,(HL)
	CALL	I2C_PUTBYTE_ACK		; PUT DATA ON BUS
	JP	NZ,DS3_SET_ERR
	INC	HL
	DJNZ	DS3_ST1
;
	CALL	I2C_STOP
;
	CALL	DS3_CLROSF		; TIME NOW VALID: CLEAR OSF
	JP	NZ,DS3_SET_ERR
;
	; RELOAD THE SOFT CLOCK FROM THE CHIP
	CALL	DS3_RDC
	CALL	Z,DS3_XLAT
	XOR	A			; CLEAR THE RESYNC FLAG
	LD	(DS3_SYNCF),A
	RET
;
DS3_SET_ERR:
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; DETECT DS3231 PRESENCE, PROBE ONLY, NO DATA PHASE
; RETURNS Z IF PRESENT, NZ IF NOT
;
DS3_DETECT:
	CALL	I2C_WAIT_FOR_BB
	RET	NZ			; BUS BUSY, ASSUME NOT PRESENT
;
	LD	A,DS3_WRITE		; SLAVE ADDRESS (WRITE)
	CALL	I2C_START_ADDR		; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_ACK	; DID IT ACK?
	PUSH	AF			; SAVE RESULT
	CALL	I2C_STOP		; RELEASE BUS EITHER WAY
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; WRITE CONTROL REGISTER: OSCILLATOR RUNNING, SQUARE WAVE MODE, 1HZ
;
DS3_INITCTL:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	JP	NZ,DS3_SET_ERR
;
	LD	A,DS3231_REG_CTL
	CALL	I2C_PUTBYTE_PIN
	JP	NZ,DS3_SET_ERR
;
	LD	A,DS3231_CTL_INIT
	CALL	I2C_PUTBYTE_ACK
	JP	NZ,DS3_SET_ERR
;
	CALL	I2C_STOP
	XOR	A
	RET
;
;-----------------------------------------------------------------------------
; READ STATUS REGISTER, RETURN VALUE IN A
;
DS3_RDSTA:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	JP	NZ,DS3_SET_ERR
;
	LD	A,DS3231_REG_STA
	CALL	I2C_PUTBYTE_PIN
	JP	NZ,DS3_SET_ERR
;
	CALL	I2C_REPSTART
;
	LD	A,DS3_READ
	CALL	I2C_PUTBYTE
;
	CALL	I2C_PREPNACK		; SINGLE BYTE, NACK IT NOW
	CALL	I2C_WAIT_FOR_PIN
	JP	NZ,DS3_SET_ERR
	CALL	I2C_GETBYTE
	LD	B,A			; SAVE STATUS
;
	CALL	I2C_WAIT_FOR_PIN
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	LD	A,B
	RET	Z			; Z: A = STATUS VALUE
	RET				; NZ: ERROR
;
;-----------------------------------------------------------------------------
; CLEAR OSCILLATOR STOP FLAG (CALLED AFTER A VALID TIME WRITE)
;
DS3_CLROSF:
	CALL	DS3_RDSTA
	RET	NZ
	AND	01111111B		; CLEAR OSF, KEEP OTHER BITS
	LD	C,A
;
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	JP	NZ,DS3_SET_ERR
;
	LD	A,DS3231_REG_STA
	CALL	I2C_PUTBYTE_PIN
	JP	NZ,DS3_SET_ERR
;
	LD	A,C
	CALL	I2C_PUTBYTE_ACK
	JP	NZ,DS3_SET_ERR
;
	CALL	I2C_STOP
	XOR	A
	RET
;
;-----------------------------------------------------------------------------
; AT24C32 EEPROM NVRAM (ZS-042 MODULE, I2C ADDRESS 57H)
; 4096 BYTES WITH A 2-BYTE WORD ADDRESS; THE HBIOS NVRAM INDEX (C) IS
; 8 BITS, SO EEPROM BYTES 0000H-00FFH ARE ADDRESSABLE.  5MS INTERNAL
; WRITE CYCLE, COMPLETION POLLED VIA ACK AFTER EACH WRITE.
;
; GET NVRAM BYTE
;   C: INDEX
;   E: VALUE (OUTPUT)
;
DS3_GETBYT:
	LD	A,(DS3_EEP)		; EEPROM DETECTED AT INIT?
	OR	A
	JP	Z,DS3_NOFUNC		; NO: NOT IMPLEMENTED
;
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_EE_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
;
	XOR	A			; WORD ADDRESS HIGH BYTE = 0
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,C			; WORD ADDRESS LOW BYTE = INDEX
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	CALL	I2C_REPSTART
;
	LD	A,DS3_EE_READ
	CALL	I2C_PUTBYTE
	CALL	I2C_PREPNACK		; SINGLE BYTE, NACK IT NOW
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
	CALL	I2C_GETBYTE
	LD	E,A
;
	JP	DS3_WTPIN		; WAIT FOR PIN, STOP, RETURN STATUS
;
; SET NVRAM BYTE
;   C: INDEX
;   E: VALUE
;
DS3_SETBYT:
	LD	A,(DS3_EEP)		; EEPROM DETECTED AT INIT?
	OR	A
	JP	Z,DS3_NOFUNC		; NO: NOT IMPLEMENTED
;
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_EE_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_PIN
	CALL	NZ,I2C_PINERR
;
	XOR	A			; WORD ADDRESS HIGH BYTE = 0
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,C			; WORD ADDRESS LOW BYTE = INDEX
	CALL	I2C_PUTBYTE_PIN
	CALL	NZ,I2C_PINERR
;
	LD	A,E			; DATA BYTE
	CALL	I2C_PUTBYTE_ACK
	CALL	NZ,I2C_ACKERR
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET	NZ			; BUS ERROR DURING WRITE
;
	; WAIT FOR THE INTERNAL WRITE CYCLE: ACK-POLL THE DEVICE
	LD	BC,2000			; >> 5MS AT 7.3728MHZ
DS3_EEPOLL:
	PUSH	BC
	LD	A,DS3_EE_WRITE
	CALL	I2C_START_ADDR
	CALL	I2C_WAIT_FOR_ACK	; ACK = WRITE CYCLE DONE
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	POP	BC
	RET	Z			; WRITE COMPLETE
	DEC	BC
	LD	A,B
	OR	C
	JR	NZ,DS3_EEPOLL
	OR	$FF			; TIMEOUT: NZ
	RET
;
;-----------------------------------------------------------------------------
; RTC READ
;
; 1.	ISSUE SLAVE ADDRESS WITH START CONDITION AND WRITE STATUS
; 2.	OUTPUT THE ADDRESS TO ACCESS. (00H = START OF DS3231 REGISTERS)
; 3.	OUTPUT REPEAT START TO TRANSITION TO READ PROCESS
; 4.	ISSUE SLAVE ADDRESS WITH READ STATUS
; 5.	DO A DUMMY READ
; 6.	READ 7 BYTES STARTING AT ADDRESS PREVIOUSLY SET
; 7.	END READ WITH NON-ACKNOWLEDGE
; 8.	ISSUE STOP AND RELEASE BUS
;
DS3_RDC:
	CALL	I2C_WAIT_FOR_BB
	JP	NZ,I2C_BBERR
;
	LD	A,DS3_WRITE		; SET SLAVE ADDRESS
	CALL	I2C_START_ADDR		; GENERATE START CONDITION
	CALL	I2C_WAIT_FOR_PIN	; AND ISSUE THE SLAVE ADDRESS
	JR	Z,DS3_RDC_ADDROK
;
	PUSH	AF
	CALL	I2C_STOP
	POP	AF
	RET
;
DS3_RDC_ADDROK:
	LD	A,DS3231_REG_SEC
	CALL	I2C_PUTBYTE_PIN		; PUT REGISTER ADDRESS ON BUS
	CALL	NZ,I2C_PINERR
;
	CALL	I2C_REPSTART		; REPEAT START
;
	LD	A,DS3_READ		; ISSUE CONTROL BYTE + READ
	CALL	I2C_PUTBYTE
;
	LD	HL,DS3_BUF		; READ FIRST 6 BYTES NORMALLY (ACK'D)
	LD	B,6
DS3_RL1:
	CALL	I2C_GETBYTE
	LD	(HL),A
	INC	HL
	DJNZ	DS3_RL1
;
	CALL	I2C_PREPNACK		; PREP NEGATIVE ACK FOR THE 7TH (LAST) BYTE
	CALL	I2C_WAIT_FOR_PIN	; WAIT FOR IT
	CALL	NZ,I2C_PINERR
	CALL	I2C_GETBYTE		; READ THE FINAL BYTE, NACK ALREADY SENT
	LD	(HL),A
;
; RETURNS Z/A=00 IF PIN CLEARED
; NZ/A=FF ON TIMEOUT
;
DS3_WTPIN:
	CALL	I2C_WAIT_FOR_PIN
	PUSH	AF			; SAVE RESULT -- I2C_STOP CLOBBERS A
	CALL	I2C_STOP
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; REPORT RTC DEVICE INFO
;
; THE I2C BUS ADDRESS IS REPORTED RATHER THAN THE I2C PORT ADDRESS.
; ONLY ONE CLOCK CAN BE INSTALLED IN HBIOS SO DEVICE NUMBER IS ALWAYS 0.
;
DS3_DEVICE:
	LD	D,RTCDEV_DS3231		; D := DEVICE TYPE
	LD	E,0			; E := PHYSICAL DEVICE NUMBER
	LD	H,0			; H := 0, DRIVER HAS NO MODES
	LD	L,DS3231_DEV		; L := BUS ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
;-----------------------------------------------------------------------------
; DISPLAY CLOCK INFORMATION FROM DATA STORED IN BUFFER
;
DS3_DISP:
	LD	HL,DS3_CLKTBL
DS3_CLP:
	LD	C,(HL)
	INC	HL
	LD	D,(HL)
	CALL	DS3_BCD
	INC	HL
	LD	A,(HL)
	OR	A
	RET	Z
	CALL	COUT
	INC	HL
	JR	DS3_CLP
	RET
;
DS3_CLKTBL:
	.DB	04H, 00111111B, '/'	; DD: 31
	.DB	05H, 00011111B, '/'	; MM: 12 (CENTURY MASKED)
	.DB	06H, 11111111B, ' '	; YY: 99
	.DB	02H, 00111111B, ':'	; HH: 23 (24HR MASK)
	.DB	01H, 01111111B, ':'	; MM: 59
	.DB	00H, 01111111B, 00H	; SS: 59
;
DS3_BCD:
	PUSH	HL
	LD	HL,DS3_BUF		; READ VALUE FROM
	LD	B,0			; BUFFER, INDEXED BY C
	ADD	HL,BC
	LD	A,(HL)
	AND	D			; MASK OFF UNNEEDED
	SRL	A
	SRL	A
	SRL	A
	SRL	A
	ADD	A,30H
	CALL	COUT
	LD	A,(HL)
	AND	00001111B
	ADD	A,30H
	CALL	COUT
	POP	HL
	RET
;
DS3_BUF:	.FILL	8,0		; BUFFER FOR TIME, DATE
DS3_SOFT:	.FILL	6,0		; SOFT CLOCK, HBIOS FORMAT YYMMDDHHMMSS
DS3_TICKOK:	.FILL	1,0		; NZ ONCE A TICK HAS BEEN OBSERVED
DS3_EEP:	.FILL	1,0		; NZ WHEN AT24C32 EEPROM DETECTED
DS3_DCDST:	.FILL	1,0		; NZ WHEN A DCD STORM WAS MASKED AT INIT
DS3_SYNCF:	.FILL	1,0		; NZ WHEN A BUS RESYNC IS DUE
DS3_SYNCCNT:	.FILL	2,0		; RESYNC COUNTDOWN (SECONDS)
;
;-----------------------------------------------------------------------------
; SOFT-CLOCK TICK: CALLED ONCE PER SECOND VIA VEC_SECOND (INTERRUPT
; CONTEXT -- KEEP IT LEAN, NO I2C HERE).  ADVANCES DS3_SOFT BY ONE
; SECOND, MARKS THE TICK AS ALIVE, AND ARMS THE HOURLY RESYNC FLAG.
;
DS3_SEC:
	PUSH	AF
	PUSH	BC
	PUSH	HL
;
	LD	A,1			; TICK IS ALIVE
	LD	(DS3_TICKOK),A
;
	LD	HL,(DS3_SYNCCNT)	; RESYNC COUNTDOWN
	DEC	HL
	LD	(DS3_SYNCCNT),HL
	LD	A,H
	OR	L
	JR	NZ,DS3_SEC_T
	LD	HL,DS3_RESYNC		; EXPIRED: REARM
	LD	(DS3_SYNCCNT),HL
	LD	A,1			; AND FLAG A BUS RESYNC
	LD	(DS3_SYNCF),A
DS3_SEC_T:
;
	LD	HL,DS3_SOFT+5		; SS
	CALL	DS3_INCBCD
	CP	$60
	JR	NZ,DS3_SEC_DONE
	LD	(HL),0
	DEC	HL			; MM
	CALL	DS3_INCBCD
	CP	$60
	JR	NZ,DS3_SEC_DONE
	LD	(HL),0
	DEC	HL			; HH
	CALL	DS3_INCBCD
	CP	$24
	JR	NZ,DS3_SEC_DONE
	LD	(HL),0
;
	; DATE ROLLOVER: HL -> DD AT DS3_SOFT+2
	DEC	HL
	CALL	DS3_INCBCD		; INCREMENT DAY (BCD)
	LD	C,A			; SAVE NEW DAY (BCD)
	LD	A,(DS3_SOFT+1)		; MONTH (BCD) -> BINARY IN A
	CALL	DS3_BCD2BIN
	DEC	A			; MONTH INDEX 0-11
	LD	HL,DS3_MONTBL		; MONTH LENGTH TABLE
	CALL	ADDHLA
	LD	B,(HL)			; DAYS IN MONTH
	LD	A,(DS3_SOFT)		; YEAR (BCD): LEAP IF DIVISIBLE BY 4
	CALL	DS3_BCD2BIN
	AND	$03			; Z IF LEAP YEAR
	JR	NZ,DS3_SEC_NL		; NOT LEAP: SKIP FEB ADJUSTMENT
	LD	A,(DS3_SOFT+1)
	CP	$02			; FEBRUARY?
	JR	NZ,DS3_SEC_NL
	INC	B			; 29 DAYS IN LEAP FEBRUARY
DS3_SEC_NL:
	LD	A,C			; NEW DAY (BCD) -> BINARY
	CALL	DS3_BCD2BIN
	LD	HL,DS3_SOFT+2
	CP	B			; PAST END OF MONTH?
	JR	Z,DS3_SEC_DONE		; DAY == DAYS-IN-MONTH IS STILL VALID
	JR	C,DS3_SEC_DONE		; DAY < DAYS-IN-MONTH: VALID
	LD	(HL),1			; FIRST OF NEXT MONTH
	DEC	HL			; MONTH
	CALL	DS3_INCBCD
	CP	$13			; PAST DECEMBER?
	JR	NZ,DS3_SEC_DONE
	LD	(HL),1			; JANUARY
	DEC	HL			; YEAR
	CALL	DS3_INCBCD		; 99 -> 00 VIA DAA CARRY, FINE
DS3_SEC_DONE:
	POP	HL
	POP	BC
	POP	AF
DS3_SECCHAIN:
	JP	0			; CHAIN TO PREVIOUS HANDLER (PATCHED)
;
; INCREMENT THE BCD BYTE AT (HL).  RETURNS THE NEW VALUE IN A.
;
DS3_INCBCD:
	LD	A,(HL)
	INC	A
	DAA
	LD	(HL),A
	RET
;
; CONVERT BCD IN A (00-99) TO BINARY IN A.  CLOBBERS NOTHING ELSE.
;
DS3_BCD2BIN:
	PUSH	BC
	LD	B,A
	AND	$F0			; TENS
	RRCA
	RRCA
	RRCA
	RRCA
	LD	C,A			; TENS*2 = TENS*10/5... USE C=TENS
	ADD	A,A			; TENS*2
	ADD	A,A			; TENS*4
	ADD	A,C			; TENS*5
	ADD	A,A			; TENS*10
	LD	C,A
	LD	A,B
	AND	$0F			; UNITS
	ADD	A,C
	POP	BC
	RET
;
; DAYS PER MONTH, INDEX 0 = JANUARY (FEBRUARY IS 28, ADJUSTED FOR LEAP)
;
DS3_MONTBL:
	.DB	31,28,31,30,31,30,31,31,30,31,30,31
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_DS3231	.EQU	$
SIZ_DS3231	.EQU	END_DS3231 - ORG_DS3231
;
	MEMECHO	"DS3231 occupies "
	MEMECHO	SIZ_DS3231
	MEMECHO	" bytes.\n"
