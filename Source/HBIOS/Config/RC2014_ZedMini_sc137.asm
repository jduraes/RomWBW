;
;==================================================================================================
;   ROMWBW CUSTOM BUILD: RC2014 ZED MINI (Z80) + SC137 I2C MASTER + DS3231 RTC
;==================================================================================================
;
; INHERITS RC2014_std AND ADDS:
;   - SC137 I2C BUS MASTER (BIT-BANGED, PORT $0C, SDA=BIT7, SCL=BIT0)
;   - DS3231 RTC AT I2C ADDRESS $68 VIA THE SC137
;   - DS1302 LATCH DRIVER DISABLED (NOT FITTED ON THIS MACHINE)
;
; BUILD:  Source\HBIOS\Build.cmd RC2014 ZedMini_sc137 rc2014sc137
; OUTPUT: Binary\rc2014sc137.rom / .upd
;
#DEFINE AUTO_CMD	""		; AUTO CMD WHEN BOOT_TIMEOUT IS ENABLED
#DEFINE DEFSERCFG	SER_115200_8N1 | SER_RTS	; DEFAULT SERIAL CONFIGURATION
;
#INCLUDE "Config/RC2014_std.asm"
;
DSRTCENABLE	.SET	FALSE		; DSRTC: NO DS-1302 FITTED
FDENABLE	.SET	FALSE		; FD: NO FLOPPY CONTROLLER FITTED (HBIOS SPACE)
;
I2CBITENABLE	.SET	TRUE		; I2CBIT: SC137 BIT-BANG I2C MASTER
I2CBITBASE	.SET	$0C		; I2CBIT: SC137 BASE I/O ADDRESS
;
DS3231RTCENABLE	.SET	TRUE		; DS3231RTC: DS-3231 I2C CLOCK VIA SC137
;
; DS3231 1HZ SQW OUTPUT IS WIRED TO THE 16C550 DCD PIN (PLCC PIN 42):
; THE UART MODEM-STATUS INTERRUPT DRIVES THE HBIOS TICK (2 EDGES/SEC).
; REQUIRES REAL INTERRUPTS: THE 16C550 INTRPT PIN REACHES Z80 /INT,
; AND THE UART DRIVER MUST HOOK IM1 TO SERVICE THE MODEM-STATUS INT.
INTMODE		.SET	1		; INTMODE: Z80 INTERRUPT MODE 1 (REQUIRED FOR SQW TICK)
UARTINTS	.SET	TRUE		; UARTINTS: INTERRUPT-DRIVEN UART (REQUIRED FOR SQW TICK)
TICKFREQ	.SET	2		; TICKFREQ: 2 SQW EDGES PER SECOND
