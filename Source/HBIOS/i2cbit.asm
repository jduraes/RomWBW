;==================================================================================================
; BITBANGED I2C BUS MASTER
; BASED ON THE WORK OF STEPHEN C COUSINS
; https://smallcomputercentral.com/scm-apps/scm-app-i2c-demo-version-2-2/
;
; DROP IN REPLACEMENT FOR I2CPCF.ASM ON BOARDS WITH NO REAL PCF8584 CHIP
; SC137 "I2C BUS MASTER MODULE (RC2014)"
; SC608 "RCBUS I2C BUS MASTER"
; SC704 "RCBUS I2C BUS MASTER"
; SELECTED VIA I2CBITENABLE MUTUALLY EXCLUSIVE WITH I2CPCFENABLE
;
; SAME PUBLIC LABELS AS I2CPCF.ASM SO LCDI2C.ASM/DS7RTC.ASM/DS3231RTC.ASM
; RUN UNMODIFIED AGAINST EITHER BACKEND.
;
; SC137 PORT PROTOCOL (VERIFIED ON HARDWARE 2026-10-07, PORT $0C):
;   WRITE 1 TO A LINE BIT = RELEASE LINE (PULLED HIGH BY PULL-UP)
;   WRITE 0 TO A LINE BIT = DRIVE LINE LOW
;   READ RETURNS THE ACTUAL LINE STATES (NOT THE LATCHED VALUE),
;   SO CLOCK STRETCHING AND STUCK-BUS CONDITIONS ARE VISIBLE.
;   SDA = BIT 7, SCL = BIT 0 (BOTH DIRECTIONS).  BITS 1-6 ARE
;   UNUSED ON SC137 BUT ARE PRESERVED VIA I2CBIT_SHADOW FOR PORTS
;   THAT SHARE THE BYTE WITH OTHER FUNCTIONS.
;
; CLOCK STRETCHING IS HONOURED: EVERY SCL RELEASE POLLS THE LINE
; UNTIL IT IS ACTUALLY HIGH, WITH A TIMEOUT (I2CBIT_STRTO).
;
; FIXME
; FOR SYSTEMS WITH HIGHER CLOCK SPEEDS A DELAY WILL NEED TO BE ADDED
;
; **********************************************************************
; **********************************************************************
; I2C bus master driver
; Source Stephen C Cousins
; **********************************************************************
; **********************************************************************
;
; I2C transfer sequence
;   +-------+  +---------+  +---------+     +---------+  +-------+
;   | Start |  | Address |  | Data    | ... | Data    |  | Stop  |
;   |       |  | frame   |  | frame 1 |     | frame N |  |       |
;   +-------+  +---------+  +---------+     +---------+  +-------+
;
; Start condition                     Stop condition
; Output by master device             Output by master device
;       ----+                                      +----
; SDA       |                         SDA          |
;           +-------                        -------+
;       -------+                                +-------
; SCL          |                      SCL       |
;              +----                        ----+
;
#IF (I2CPCFENABLE)
	.ECHO	"*** I2CPCF DRIVER CANNOT BE USED WITH I2CBIT DRIVER!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
I2CBIT_BASE	.EQU	I2CBITBASE
I2CBIT_SDA	.EQU	7		; SDA BIT NUMBER, READ AND WRITE
I2CBIT_SCL	.EQU	0		; SCL BIT NUMBER, READ AND WRITE
I2CBIT_QUIES	.EQU	10000001B	; BOTH LINES IDLE (RELEASED)
I2CBIT_LINES	.EQU	10000001B	; MASK OF BITS OWNED BY I2C
;
; SAME BIT POSITION AS THE REAL PCF8584'S LRB
; SO I2CBIT_WAIT_FOR_ACK'S Z/NZ CONTRACT MATCHES I2CPCF.ASM
; NO REAL STATUS REGISTER BEHIND IT HERE
;
I2CBIT_LRB	.EQU	00001000B
;
; CLOCK STRETCH TIMEOUT, BUSY LOOP ITERATIONS.  AT 7.3728MHZ ONE
; ITERATION IS ROUGHLY 4US, SO $4000 IS ~65MS.
;
I2CBIT_STRTO	.EQU	$4000
;
	DEVECHO	"I2CBIT: IO="
	DEVECHO	I2CBIT_BASE
	DEVECHO	"\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_I2CBIT	.EQU	$
;
	.DW	SIZ_I2CBIT		; MODULE SIZE
	.DW	I2CBIT_INITPHASE	; ADR OF INIT PHASE HANDLER
;
I2CBIT_INITPHASE:
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,I2CBIT_INIT		; DO INIT
	RET				; DONE
;
;-----------------------------------------------------------------------------
; WRITE THE SDA/SCL BITS OF A TO THE PORT, PRESERVING ALL OTHER
; OUTPUT BITS VIA THE SHADOW REGISTER.
; CLOBBERS AF ONLY.
;
I2CBIT_OUT:
	PUSH	BC
	LD	B,A			; SAVE FULL INCOMING VALUE
	AND	I2CBIT_LINES		; KEEP ONLY SDA/SCL
	LD	C,A
	LD	A,(I2CBIT_SHADOW)	; OTHER BITS FROM SHADOW
	AND	~I2CBIT_LINES & $FF
	OR	C			; MERGE
	LD	(I2CBIT_SHADOW),A	; UPDATE SHADOW
	OUT	(I2CBIT_BASE),A		; COMMIT TO HARDWARE
	LD	A,B			; RESTORE A
	POP	BC
	RET
;
;-----------------------------------------------------------------------------
; RELEASE SCL (WRITE 1) AND WAIT FOR THE LINE TO ACTUALLY GO HIGH.
; HONOURS CLOCK STRETCHING.  OTHER LINE BIT UNCHANGED (FROM SHADOW).
; RETURNS Z IF SCL WENT HIGH, NZ ON TIMEOUT.
; CLOBBERS AF, HL PRESERVED.
;
I2CBIT_SCLHI:
	PUSH	HL
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SCL		; RELEASE SCL
	CALL	I2CBIT_OUT
	LD	HL,I2CBIT_STRTO
I2CBIT_SCLHI1:
	IN	A,(I2CBIT_BASE)
	BIT	I2CBIT_SCL,A
	JR	NZ,I2CBIT_SCLHI2		; LINE IS HIGH, DONE
	DEC	HL
	LD	A,H
	OR	L
	JR	NZ,I2CBIT_SCLHI1		; KEEP WAITING
	POP	HL
	OR	$FF			; NZ: TIMEOUT, SCL STUCK LOW
	RET
I2CBIT_SCLHI2:
	POP	HL
	XOR	A			; Z: OK
	RET
;
;-----------------------------------------------------------------------------
; DRIVE SCL LOW (WRITE 0), SDA UNCHANGED.  CLOBBERS AF.
;
I2CBIT_SCLLO:
	LD	A,(I2CBIT_SHADOW)
	AND	~(1 << I2CBIT_SCL) & $FF
	JP	I2CBIT_OUT
;
;-----------------------------------------------------------------------------
; BUS RECOVERY: IF SDA IS STUCK LOW A SLAVE IS MID-TRANSACTION.
; CLOCK SCL UP TO 9 TIMES WITH SDA RELEASED UNTIL THE SLAVE LETS
; GO, THEN ISSUE A STOP.  RETURNS Z IF THE BUS RECOVERED, NZ IF
; SCL IS STUCK LOW (UNRECOVERABLE) OR SDA NEVER RELEASED.
;
I2CBIT_RECOVER:
	PUSH	BC
	LD	B,9
I2CBIT_REC1:
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; RELEASE SDA
	AND	~(1 << I2CBIT_SCL) & $FF ; SCL LOW
	CALL	I2CBIT_OUT
	CALL	I2CBIT_SCLHI		; RELEASE SCL, WAIT HIGH
	JR	NZ,I2CBIT_REC2		; SCL STUCK LOW, GIVE UP
	IN	A,(I2CBIT_BASE)
	BIT	I2CBIT_SDA,A
	JR	NZ,I2CBIT_REC3		; SDA RELEASED, RECOVERED
	CALL	I2CBIT_SCLLO		; NEXT PULSE
	DJNZ	I2CBIT_REC1
I2CBIT_REC2:
	POP	BC
	OR	$FF			; NZ: RECOVERY FAILED
	RET
I2CBIT_REC3:
	CALL	I2C_STOP		; CLOSE OUT THE TRANSACTION
	POP	BC
	XOR	A			; Z: RECOVERED
	RET
;
;-----------------------------------------------------------------------------
; NO REAL CHIP TO PROBE.  VERIFY THE BUS IDLES HIGH, RECOVER A STUCK
; BUS IF NEEDED, THEN TOGGLE SDA BOTH WAYS AND CONFIRM READBACK.
; A STATIC COMPARE CAN'T TELL FLOATING FROM WIRED.
;
I2CBIT_INIT:
	CALL	NEWLINE
	PRTS("I2CBIT: IO=0x$")
	LD	A,I2CBIT_BASE
	CALL	PRTHEXBYTE
	CALL	PC_SPACE
;
	LD	A,I2CBIT_QUIES		; BOTH LINES RELEASED
	LD	(I2CBIT_SHADOW),A	; INITIALISE SHADOW
	OUT	(I2CBIT_BASE),A
	CALL	DELAY
;
	IN	A,(I2CBIT_BASE)		; BUS IDLE?
	AND	I2CBIT_LINES
	CP	I2CBIT_LINES
	JR	Z,I2CBIT_IDLE
;
	CALL	I2CBIT_RECOVER		; TRY TO UNSTICK IT
	JR	NZ,I2CBIT_STUCK
	IN	A,(I2CBIT_BASE)
	AND	I2CBIT_LINES
	CP	I2CBIT_LINES
	JR	Z,I2CBIT_IDLE
I2CBIT_STUCK:
	PRTS("BUS STUCK$")
	JR	I2CBIT_FAIL
;
I2CBIT_IDLE:
	LD	A,(I2CBIT_SHADOW)
	RES	I2CBIT_SDA,A		; DRIVE SDA LOW, SCL STAYS RELEASED
	CALL	I2CBIT_OUT
	IN	A,(I2CBIT_BASE)
	BIT	I2CBIT_SDA,A
	JR	NZ,I2CBIT_FAIL		; SDA DIDN'T GO LOW
	LD	A,(I2CBIT_SHADOW)
	SET	I2CBIT_SDA,A		; RELEASE SDA AGAIN
	CALL	I2CBIT_OUT
	IN	A,(I2CBIT_BASE)
	BIT	I2CBIT_SDA,A
	JR	Z,I2CBIT_FAIL		; SDA DIDN'T GO HIGH
	XOR	A
	RET
;
I2CBIT_FAIL:
	CALL	I2CBIT_INIERR
	LD	A,ERR_NOHW
	LD	(I2C_FAIL_FLAG),A
	RET
;
I2C_FAIL_FLAG:
	.DB	0
;
;-----------------------------------------------------------------------------
; GENERATE START CONDITION AND SHIFT THE ADDRESS BYTE (A ON ENTRY)
; REAL PCF8584 DOES THIS AUTONOMOUSLY AFTER S0/S1 ARE WRITTEN
; BITBANGED, BOTH HALVES HAPPEN HERE, SYNCHRONOUSLY
;
I2C_START_ADDR:
	LD	(I2CBIT_XMIT),A
I2C_START:
	XOR	A
	LD	(I2CBIT_STRERR),A	; CLEAR STICKY STRETCH ERROR
	LD	A,(I2CBIT_SHADOW)
	OR	I2CBIT_LINES		; RELEASE BOTH LINES
	CALL	I2CBIT_OUT
	RES	I2CBIT_SDA,A		; START: SDA FALLS WHILE SCL STAYS HIGH
	CALL	I2CBIT_OUT
	RES	I2CBIT_SCL,A		; SCL FALLS TOO, BOTH LOW NOW
	CALL	I2CBIT_OUT
	LD	A,(I2CBIT_XMIT)		; SHIFT WHATEVER'S BUFFERED, MATCHES REAL
	JP	I2CBIT_SHIFTOUT		; HARDWARE'S "RESEND LAST S0 BYTE" BEHAVIOR
;
;-----------------------------------------------------------------------------
; REPEATED START, NO BYTE SHIFT
;
I2C_REPSTART:
	LD	A,1
	LD	(I2CBIT_RD_DUMMY),A
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; RELEASE SDA FIRST
	CALL	I2CBIT_OUT
	CALL	I2CBIT_SCLHI		; RELEASE SCL, WAIT FOR HIGH
	LD	A,(I2CBIT_SHADOW)
	RES	I2CBIT_SDA,A		; REPEATED START: SDA FALLS WHILE SCL HIGH
	CALL	I2CBIT_OUT
	RES	I2CBIT_SCL,A
	CALL	I2CBIT_OUT
	RET
;
;-----------------------------------------------------------------------------
; STOP CONDITION.  CLOBBERS A, PRESERVES FLAGS (DS7RTC RELIES ON THIS).
;
I2C_STOP:
	PUSH	AF
	LD	A,(I2CBIT_SHADOW)
	AND	~I2CBIT_LINES & $FF	; SDA=0, SCL=0
	CALL	I2CBIT_OUT
	CALL	I2CBIT_SCLHI		; RELEASE SCL, WAIT HIGH
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; STOP: SDA RISES WHILE SCL STAYS HIGH
	CALL	I2CBIT_OUT
	POP	AF
	RET
;
;-----------------------------------------------------------------------------
; PUT ONE BYTE ON THE BUS, NO ACK CHECK
;
I2C_PUTBYTE:
	JP	I2CBIT_SHIFTOUT
;
;-----------------------------------------------------------------------------
; PUT ONE BYTE, FALLS THROUGH TO I2C_WAIT_FOR_PIN
;
I2C_PUTBYTE_PIN:
	CALL	I2CBIT_SHIFTOUT
;
; NO SHIFT REGISTER TO POLL, FALLS INTO THE REAL ACK CHECK
;
I2C_WAIT_FOR_PIN:
	JR	I2C_WAIT_FOR_ACK
;
;-----------------------------------------------------------------------------
; PUT ONE BYTE, FALLS THROUGH TO THE ACK CHECK
;
I2C_PUTBYTE_ACK:
	CALL	I2CBIT_SHIFTOUT
;	FALLS THROUGH
;
; RETURN Z/A=0 IF ACK RECEIVED, NZ IF NOT.  A STRETCH TIMEOUT
; DURING THE BYTE IS ALSO REPORTED AS NZ (STICKY I2CBIT_STRERR).
;
I2C_WAIT_FOR_ACK:
	LD	A,(I2CBIT_STRERR)	; STRETCH TIMEOUT DURING SHIFT?
	OR	A
	RET	NZ
	LD	A,(I2CBIT_STATUS)
	AND	I2CBIT_LRB
	RET	Z
	LD	A,1
	OR	A
	RET
;
;-----------------------------------------------------------------------------
; NO REAL BUS BUSY REGISTER ON A BITBANGED SINGLE MASTER BUS, ALWAYS FREE.
;
I2C_WAIT_FOR_BB:
	XOR	A
	RET
;
;-----------------------------------------------------------------------------
; READ PATH
; I2C_GETBYTE AND I2C_READI2C SHARE ONE BODY, SAME COLLAPSE AS
; I2C_PUTBYTE_PIN ABOVE
;
I2C_GETBYTE:
I2C_READI2C:
	LD	A,(I2CBIT_RD_DUMMY)	; DUMMY READ ARMED BY I2C_REPSTART?
	OR	A
	JR	Z,I2CBIT_CLOCKIN
	XOR	A			; YES, CONSUME IT, NO BUS ACTIVITY
	LD	(I2CBIT_RD_DUMMY),A
	RET
;
; CLOCK IN ONE BYTE, MSB FIRST
; SENDS ACK UNLESS I2CBIT_NACKPEND IS SET, CONSUMED HERE
; RETURNS BYTE IN A, Z ALWAYS SET (STRETCH TIMEOUT SETS I2CBIT_STRERR)
; SDA IS RELEASED ONCE BEFORE THE LOOP AND STAYS HIGH FOR ALL 8 BITS
;
I2CBIT_CLOCKIN:
	PUSH	BC
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; RELEASE SDA FOR THE WHOLE
	CALL	I2CBIT_OUT		; RECEIVE PHASE, SLAVE DRIVES IT
	LD	C,0			; C = ACCUMULATED BYTE
	LD	B,8			; B = DJNZ COUNTER
I2CBIT_CI_LP:
	CALL	I2CBIT_SCLHI		; RELEASE SCL, WAIT STRETCH
	JR	NZ,I2CBIT_CI_TO		; TIMEOUT, ABORT BYTE
	IN	A,(I2CBIT_BASE)		; SAMPLE WHILE SCL HIGH
	RL	C			; SHIFT ACCUMULATOR, MSB FIRST
	BIT	I2CBIT_SDA,A
	JR	Z,I2CBIT_CI_B0
	SET	0,C
I2CBIT_CI_B0:
	CALL	I2CBIT_SCLLO		; SCL LOW, SDA STILL RELEASED
	DJNZ	I2CBIT_CI_LP
;
	LD	A,(I2CBIT_NACKPEND)
	OR	A
	JR	NZ,I2CBIT_CI_NACK
	LD	A,(I2CBIT_SHADOW)
	RES	I2CBIT_SDA,A		; ACK: DRIVE SDA LOW
	JR	I2CBIT_CI_STROBE
I2CBIT_CI_NACK:
	XOR	A
	LD	(I2CBIT_NACKPEND),A	; ONE-SHOT, CONSUMED
	LD	A,(I2CBIT_SHADOW)	; NACK: SDA STAYS RELEASED
I2CBIT_CI_STROBE:
	CALL	I2CBIT_OUT		; COMMIT ACK/NACK BIT
	CALL	I2CBIT_SCLHI		; STROBE SCL, WAIT STRETCH
	CALL	I2CBIT_SCLLO
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; RELEASE SDA, READY FOR NEXT BYTE/STOP
	CALL	I2CBIT_OUT
;
	LD	A,C			; RETURN THE RECEIVED BYTE
	POP	BC
	CP	A			; FORCE Z
	RET
;
I2CBIT_CI_TO:
	LD	A,$FF
	LD	(I2CBIT_STRERR),A
	POP	BC
	XOR	A			; RETURN GARBAGE ZERO BYTE
	CP	A			; Z, ERROR SURFACES AT NEXT WAIT
	RET
;
I2CBIT_RD_DUMMY:
	.DB	0
I2CBIT_NACKPEND:
	.DB	0
I2CBIT_STRERR:
	.DB	0
;
;-----------------------------------------------------------------------------
; PREP NACK FOR THE LAST BYTE OF A READ
; NO STATUS REGISTER TO PRESET, JUST A FLAG I2CBIT_CLOCKIN CONSUMES NEXT
;
I2C_PREPNACK:
	LD	A,1
	LD	(I2CBIT_NACKPEND),A
	RET
;
; SHIFT OUT 8 BITS (A), MSB FIRST, SAMPLE ACK ON THE 9TH CLOCK
; ENTER/EXIT WITH SCL LOW.  UPDATES I2CBIT_STATUS (I2CBIT_LRB:
; 0=ACK, 1=NACK) AND I2CBIT_STRERR ON STRETCH TIMEOUT.
;
I2CBIT_SHIFTOUT:
	PUSH	BC
	LD	C,A			; C = BYTE BEING SHIFTED
	LD	B,8			; B = DJNZ COUNTER
I2CBIT_SO_LP:
	RL	C			; NEXT BIT INTO CARRY
	LD	A,(I2CBIT_SHADOW)	; LD PRESERVES FLAGS
	JR	NC,I2CBIT_SO_0
	SET	I2CBIT_SDA,A		; RELEASE SDA (HIGH)
	JR	I2CBIT_SO_CLK
I2CBIT_SO_0:
	RES	I2CBIT_SDA,A		; DRIVE SDA LOW
I2CBIT_SO_CLK:
	RES	I2CBIT_SCL,A		; SCL LOW
	CALL	I2CBIT_OUT		; SDA SETTLED, SCL LOW
	CALL	I2CBIT_SCLHI		; RELEASE SCL, SLAVE SAMPLES SDA
	JR	NZ,I2CBIT_SO_TO		; STRETCH TIMEOUT
	CALL	I2CBIT_SCLLO		; SCL LOW, READY FOR NEXT BIT
	DJNZ	I2CBIT_SO_LP
;
; 9TH CLOCK, RELEASE SDA AND SAMPLE THE SLAVE'S ACK
;
	LD	A,(I2CBIT_SHADOW)
	OR	1 << I2CBIT_SDA		; RELEASE SDA, SCL STAYS LOW
	CALL	I2CBIT_OUT
	CALL	I2CBIT_SCLHI		; SCL HIGH, SLAVE MAY PULL SDA LOW
	JR	NZ,I2CBIT_SO_TO
	IN	A,(I2CBIT_BASE)		; SAMPLE ACK BIT WHILE SCL HIGH
	LD	C,A			; SAVE SAMPLED BYTE
	CALL	I2CBIT_SCLLO
;
	XOR	A			; DEFAULT (ACK) STATUS VALUE
	BIT	I2CBIT_SDA,C
	JR	Z,I2CBIT_SO_ACKD
	LD	A,I2CBIT_LRB
I2CBIT_SO_ACKD:
	LD	(I2CBIT_STATUS),A
	POP	BC
	RET
;
I2CBIT_SO_TO:
	LD	A,$FF
	LD	(I2CBIT_STRERR),A
	LD	A,I2CBIT_LRB		; REPORT AS NACK TOO
	LD	(I2CBIT_STATUS),A
	CALL	I2CBIT_SCLLO
	POP	BC
	OR	$FF
	RET
;
I2CBIT_STATUS:	.DB	0
I2CBIT_XMIT:	.DB	0
I2CBIT_SHADOW:	.DB	I2CBIT_QUIES
;
;-----------------------------------------------------------------------------
; DISPLAY ERROR MESSAGES
; ONLY WHAT RTC/LCD DRIVERS CALL DIRECTLY
;
I2CBIT_INIERR:
	PUSH	HL
	LD	HL,I2CBIT_NOI2C
	JR	I2CBIT_PRTERR
;
I2CBIT_ACKERR:
	PUSH	HL
	LD	HL,I2CBIT_ACKFAIL
	JR	I2CBIT_PRTERR
;
I2CBIT_BBERR:
	PUSH	HL
	LD	HL,I2CBIT_BBFAIL
	JR	I2CBIT_PRTERR
;
I2CBIT_PINERR:
	PUSH	HL
	LD	HL,I2CBIT_PINFAIL
;	FALLS THROUGH
;
I2CBIT_PRTERR:
	CALL	PRTSTR
	POP	HL
	; FORCE NZ THIS IS THE ERROR PATH
	OR	$FF
	RET
;
I2CBIT_NOI2C	.DB	"NOT PRESENT$"
I2CBIT_ACKFAIL	.DB	"FAILED TO RECEIVE ACKNOWLEDGE$"
I2CBIT_PINFAIL	.DB	"PIN FAIL$"
I2CBIT_BBFAIL	.DB	"BUS BUSY$"
;
I2C_ACKERR	.EQU	I2CBIT_ACKERR
I2C_BBERR	.EQU	I2CBIT_BBERR
I2C_PINERR	.EQU	I2CBIT_PINERR
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_I2CBIT	.EQU	$
SIZ_I2CBIT	.EQU	END_I2CBIT - ORG_I2CBIT
;
	MEMECHO	"I2CBIT occupies "
	MEMECHO	SIZ_I2CBIT
	MEMECHO	" bytes.\n"
